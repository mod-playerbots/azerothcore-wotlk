local barButtons = nil

local function ActionButtons()
    -- An EMPTY result is never cached. A replacement bar addon may not have built its buttons
    -- when this file first looks, and Blizzard's own are not there at all until the UI has
    -- loaded -- so caching "none" once would leave the strips off for the session.
    if barButtons and #barButtons > 0 then
        return barButtons
    end
    barButtons = {}
    for _, entry in ipairs(BAR_PREFIXES) do
        for i = 1, entry[2] do
            local btn = _G[entry[1] .. i]
            if btn and btn.GetWidth then
                barButtons[#barButtons + 1] = btn
            end
        end
    end
    return barButtons
end

-- The real spell id behind a SPELL BOOK index.
--
-- 3.3.5's GetActionInfo does not hand back a spell id for a spell action. It hands back the
-- index of that spell in the character's spell book, together with which book it is in -- so
-- Heroic Strike in the first action slot came out as 32, which is not a spell at all, and
-- GetSpellInfo(32) answered nothing. That is exactly what the strips were drawing: nothing.
--
-- The link is the only place the client will say the number out loud:
-- "|cff71d5ff|Hspell:78|h[Heroic Strike]|h|r". Reading it back out is the standard move on this
-- client and it is stable -- the id sits in the hyperlink the game builds for chat.
local function SpellIdFromBook(index, book)
    if GetSpellLink == nil then
        return nil
    end
    local ok, link = pcall(GetSpellLink, index, book or "spell")
    if ok and type(link) == "string" then
        local sid = tonumber(string.match(link, "spell:(%d+)"))
        if sid and sid > 0 then
            return sid
        end
    end
    return nil
end

-- Which spell a button is showing, or nil.
--
-- Paged through ActionButton_GetPagedID where it exists, because a stance or a bar page moves
-- what slot 1 means and the raw `action` field is then the unpaged one. Only real spells: a
-- macro holds a name rather than an id in 3.3.5 and resolving it would be guesswork, and an item
-- or a mount has no practice behind it either way.
local function ActionSpell(btn)
    local slot = btn.action
    if ActionButton_GetPagedID then
        local ok, paged = pcall(ActionButton_GetPagedID, btn)
        if ok and paged then
            slot = paged
        end
    end
    if slot == nil or not HasAction(slot) then
        return nil
    end
    local kind, id, subType = GetActionInfo(slot)
    if kind ~= "spell" or not id or id <= 0 then
        return nil
    end
    local sid = SpellIdFromBook(id, subType)
    if sid then
        return sid
    end
    -- A client that already answers with the spell id itself still works. Tried SECOND, because
    -- a book index and a spell id are both small integers and the wrong one resolves to a real
    -- ability often enough to be worse than nothing.
    if GetSpellInfo(id) then
        return id
    end
    return nil
end

-- The strip itself, made once per button and kept.
--
-- In its own frame rather than as a texture on the button, and six levels up, so the cooldown
-- swipe cannot draw over it -- the swipe is a frame, and a texture on the button would lose to
-- it exactly when the reader is pressing the button.
local function EnsureStrip(btn)
    local strip = practiceStrips[btn]
    if strip then
        return strip
    end
    -- The fill and nothing else. There was a dark backing behind it spanning the whole icon --
    -- meant to be the empty part of the bar -- and the user's call is that it goes: an early rank
    -- was then a black slab with a sliver of white at one end, which reads as a dark bar however
    -- white the sliver is. What is left is the progress itself, and the icon underneath is what
    -- the rest of the width shows.
    --
    -- On its own frame, six levels above the button, so neither the cooldown swipe nor anything
    -- else the button draws can come out on top of it. The swipe is a frame, and a texture on the
    -- button would lose to it exactly when the reader is pressing the button.
    local holder = CreateFrame("Frame", nil, btn)
    holder:SetAllPoints(btn)
    holder:SetFrameLevel(btn:GetFrameLevel() + 6)
    -- Flat colour rather than Blizzard's status bar art. The art is a soft vertical gradient
    -- built to be seen at bar size, and at five pixels over a bright icon it washes out into
    -- whatever is behind it -- the strip got HARDER to see when it got taller, which is the
    -- opposite of what more pixels are for.
    local fill = holder:CreateTexture(nil, "OVERLAY")
    fill:SetTexture("Interface\\Buttons\\WHITE8X8")
    fill:SetVertexColor(STRIP_FILL[1], STRIP_FILL[2], STRIP_FILL[3], STRIP_ALPHA)
    fill:SetHeight(PRACTICE_STRIP_HEIGHT)
    fill:SetPoint("BOTTOMLEFT", btn, "BOTTOMLEFT", 1, 1)
    -- The rank-up glow. Its own texture on the same holder, so it sits above the cooldown swipe
    -- for the same reason the fill does, and hidden until a rank actually lands.
    --
    -- ARTWORK layer rather than OVERLAY: the fill is the thing that must never be covered, and a
    -- glow that spills past the button's edges would otherwise draw over a neighbouring strip.
    local glow = holder:CreateTexture(nil, "ARTWORK")
    glow:SetTexture(RANK_GLOW_TEXTURE)
    if not glow:GetTexture() then
        glow:SetTexture(RANK_GLOW_FALLBACK)
    end
    glow:SetBlendMode("ADD")
    glow:SetPoint("TOPLEFT", btn, "TOPLEFT", -RANK_GLOW_PAD, RANK_GLOW_PAD)
    glow:SetPoint("BOTTOMRIGHT", btn, "BOTTOMRIGHT", RANK_GLOW_PAD, -RANK_GLOW_PAD)
    glow:SetVertexColor(RANK_GLOW_COLOR[1], RANK_GLOW_COLOR[2], RANK_GLOW_COLOR[3], 0)
    glow:Hide()
    strip = {holder = holder, fill = fill, glow = glow}
    practiceStrips[btn] = strip
    return strip
end

-- What the server says, against what is currently drawn.
--
-- Ahead of the server is the normal state between kills and is left alone -- the truth catches
-- up within a press or two, and yanking the bar back would be describing progress as loss. The
-- exception is a rank landing, where the drop is the whole point.
local function PracticeServerPct(line, pct)
    if line == nil or pct == nil then
        return
    end
    practiceSkill[line] = pct
    local drawn = predictPct[line]
    if drawn == nil or pct >= drawn or pct < drawn - PREDICT_RANK_DROP then
        predictPct[line] = pct
    end
end

local function HideStrip(btn)
    local strip = practiceStrips[btn]
    if strip then
        strip.on = false
        strip.fill:Hide()
        -- The glow goes with it. A button that has stopped showing one of our abilities is
        -- showing something else, and a celebration left burning on it would be about the wrong
        -- icon -- which is what a bar page turn in the middle of a rank-up would otherwise do.
        if strip.glow then
            strip.glowLeft = nil
            strip.glow:Hide()
        end
    end
end

-- Draw the fill at wherever the animation has got to.
local function StripApply(strip)
    local pct = strip.cur or 0
    if pct < 0 then
        pct = 0
    elseif pct > 100 then
        pct = 100
    end
    strip.fill:SetWidth(math.max(1, (strip.room or 1) * pct / 100))
end

-- One frame of movement, for every strip that is showing.
--
-- Only ever forwards. A bar that animated DOWNWARDS when a rank landed would be describing the
-- best thing that can happen to an ability as a loss; the drop is taken instantly and the flash
-- is what marks it instead.
local function StripStep(elapsed)
    for _, strip in pairs(practiceStrips) do
        -- The rank-up glow, outside the strip's own `on` test: a rank landing is worth showing
        -- even on a button whose bar is mid-refresh, and the glow is not part of the progress
        -- drawing at all.
        --
        -- Up fast, down slow. A linear fade from full reads as a light being switched off; rising
        -- over RANK_GLOW_RISE and falling over the rest reads as something happening ON the
        -- button, which is what it is.
        if strip.glowLeft then
            strip.glowLeft = strip.glowLeft - elapsed
            if strip.glowLeft <= 0 then
                strip.glowLeft = nil
                strip.glow:Hide()
            else
                local gone = RANK_GLOW_SECS - strip.glowLeft
                local a
                if gone < RANK_GLOW_RISE then
                    a = gone / RANK_GLOW_RISE
                else
                    a = strip.glowLeft / (RANK_GLOW_SECS - RANK_GLOW_RISE)
                end
                if a > 1 then a = 1 elseif a < 0 then a = 0 end
                strip.glow:SetVertexColor(RANK_GLOW_COLOR[1], RANK_GLOW_COLOR[2],
                                          RANK_GLOW_COLOR[3], a)
            end
        end
        if strip.on then
            local moved = false
            if (strip.cur or 0) < (strip.want or 0) then
                local before = strip.cur or 0
                strip.cur = math.min(strip.want, before + STRIP_GROW_PER_SEC * elapsed)
                moved = true
                -- Pulse on every whole per cent the bar passes.
                --
                -- The growth alone is not visible and cannot be made so: one Fireball is worth
                -- 0.75% of its rank (134 casts to fill one), and 0.75% of a 34 pixel strip is a
                -- quarter of a pixel. Five casts to move the width of one pixel is a bar that
                -- looks frozen while it is in fact working exactly as designed -- which is how it
                -- read from the inside: "it does not feel like it earns anything mid-fight".
                --
                -- So the feedback is made temporal instead of spatial. A per cent is a real unit
                -- here -- it is what the number in chat counts, and it is banked whether or not
                -- the fight is won -- so crossing one is worth saying, and at roughly a pulse
                -- every second cast it reads as progress rather than as noise.
                if math.floor(strip.cur) > math.floor(before) then
                    strip.flash = STRIP_FLASH_SECS
                end
            end
            if moved then
                StripApply(strip)
            end
            if strip.flash and strip.flash > 0 then
                strip.flash = strip.flash - elapsed
                local t = strip.flash / STRIP_FLASH_SECS
                if t < 0 then
                    t = 0
                end
                strip.fill:SetVertexColor(
                    STRIP_FILL[1] + (STRIP_FLASH_COLOR[1] - STRIP_FILL[1]) * t,
                    STRIP_FILL[2] + (STRIP_FLASH_COLOR[2] - STRIP_FILL[2]) * t,
                    STRIP_FILL[3] + (STRIP_FLASH_COLOR[3] - STRIP_FILL[3]) * t, STRIP_ALPHA)
            end
        end
    end
end

-- Ask about anything on a bar the server has not placed yet. Sent as ONE message however many
-- there are: "ask" shares a small allowance with opening a line of the collection, and a reader
-- with five full bars would otherwise spend the lot in a single bar refresh.
--
-- As a comma-separated STRING rather than as a table. Every other client-to-server call in this
-- addon passes plain numbers, so a table going up that way is an untested path in somebody
-- else's serialiser -- and if it does not arrive there is nothing to see: no error, no reply,
-- and strips that never appear. A string is the same shape as everything else that works.
local function AskForUnknown(ids)
    local want = {}
    for i = 1, #ids do
        local id = ids[i]
        local asked = actionAsked[id]
        local now = (GetTime and GetTime()) or 0
        if actionLine[id] == nil and (asked == nil or now - asked >= ASK_RETRY) then
            actionAsked[id] = now
            want[#want + 1] = id
        end
    end
    if #want > 0 then
        AIO.Handle(handlerName, "PracticeBars", table.concat(want, ","))
    end
end

local function PracticeBarsRefresh()
    local buttons, seen = ActionButtons(), {}
    -- Which lines were told about their pending press this pass. Cleared at the end rather than
    -- as each button is dressed, because the same ability can sit on two bars and both of them
    -- should light.
    local lit = {}
    for i = 1, #buttons do
        local btn = buttons[i]
        local spell = (barsShown and not classLessOff) and btn:IsShown()
            and ActionSpell(btn) or nil
        local line = spell and actionLine[spell]
        -- A rank of this ability has just landed: light the button it is sitting on. Checked off
        -- the NAME rather than off `line`, so it fires even for a button whose spell the server
        -- has not placed yet -- the glow is about the ability, and waiting for a round trip to
        -- celebrate would put it seconds after the message that announced it.
        if spell and next(rankGlow) ~= nil then
            local sname = GetSpellInfo(spell)
            if sname and rankGlow[sname] then
                local strip = EnsureStrip(btn)
                strip.glowLeft = RANK_GLOW_SECS
                strip.glow:SetVertexColor(RANK_GLOW_COLOR[1], RANK_GLOW_COLOR[2],
                                          RANK_GLOW_COLOR[3], 0)
                strip.glow:Show()
            end
        end
        local pct = line and (predictPct[line] or practiceSkill[line])
        if spell then
            seen[#seen + 1] = spell
        end
        if pct and pct > 0 then
            local strip = EnsureStrip(btn)
            local room = btn:GetWidth() - 2
            if room < 1 then
                room = 1
            end
            strip.room = room
            if strip.spell ~= spell then
                -- A different ability on this button. Its own progress, not a move of this one:
                -- nothing to animate and nothing to celebrate.
                strip.spell, strip.cur, strip.flash = spell, pct, nil
            elseif pct < (strip.cur or 0) then
                -- The rank landed and the bar starts again. Taken at once, and flashed.
                strip.cur, strip.flash = pct, STRIP_FLASH_SECS
            elseif strip.cur == nil then
                strip.cur = pct
            end
            if pulseLine[line] then
                strip.flash = STRIP_FLASH_SECS
            end
            strip.want = pct
            strip.on = true
            StripApply(strip)
            strip.fill:Show()
            lit[line] = true
        else
            HideStrip(btn)
        end
    end
    for line in pairs(lit) do
        pulseLine[line] = nil
    end
    -- Spent, found a button or not. See the note where rankGlow is declared.
    for name in pairs(rankGlow) do
        rankGlow[name] = nil
    end
    AskForUnknown(seen)
end

-- The answer: which line each id belongs to, and where that line stands.
function MyHandlers.PracticeBarInfo(player, ids, lines, pcts, lefts, holds)
    for i = 1, #(ids or {}) do
        local id, line = ids[i], lines and lines[i]
        if id and line then
            -- 0 means "not waiting"; kept as nil on this side so one test covers both.
            local h = holds and holds[i]
            holdLevel[line] = (h and h > 0) and h or nil
            actionLine[id] = line
            local name = GetSpellInfo(id)
            if name then
                nameLine[name] = line
            end
            if pcts and pcts[i] then
                PracticeServerPct(line, pcts[i])
            end
            if lefts and lefts[i] and lefts[i] > 0 then
                practiceNeed[line] = lefts[i]
            end
        end
    end
    PracticeBarsRefresh()
end

-- One refresh a frame at most, however many events fired into it. ACTIONBAR_SLOT_CHANGED alone
-- arrives a dozen times in a row when a bar page turns.
--
-- Parented and shown on purpose: an OnUpdate only runs on a VISIBLE frame, and an unparented one
-- is at the mercy of whatever the default happens to be.
local barWatcher = CreateFrame("Frame", nil, UIParent)
barWatcher:Show()
local barsDirty, barsClock = true, 0
-- The forward declaration near rankGlow, filled in now that there is something to dirty.
WakeBars = function() barsDirty = true end
-- One press, drawn before the kill pays for it.
--
-- The step is a damped share of what the server said was left: at "42%, ~74 presses" a press is
-- worth about (100-42)/74 of a per cent, and three quarters of that is drawn. Held to
-- PREDICT_AHEAD_MAX in front of the last real figure so that a spammer -- whose extra presses
-- the share cap will pay nothing for -- runs out of rope quickly rather than watching a bar fill
-- that the kill then has to contradict.
local function PracticePredictPress(line)
    -- Out of combat nothing is being earned, so nothing may be drawn. The server stopped
    -- crediting presses made outside a fight on 2026-09-19 (OnSpellCast); this is the same rule
    -- on the client, and without it the bar still climbed for a Rejuvenation cast in an empty
    -- field -- a promise the next kill then had to take back. Reported against Rejuvenation
    -- (774), true of every line.
    --
    -- Player combat only, not "an enemy is targeted": the server files a press with an enemy
    -- behind it against that creature, but this side knows only the spell's NAME, never what it
    -- was aimed at, so a heal cast on yourself with a mob under the cursor would read as a
    -- fight. The cost is the opening cast of a pull, which lands a moment before the combat
    -- flag does and is now drawn one press late. The kill's own figure corrects it either way.
    if UnitAffectingCombat and not UnitAffectingCombat("player") then
        return
    end
    local server = practiceSkill[line]
    local left = practiceNeed[line]
    if server == nil or left == nil or left < 1 then
        return
    end
    local drawn = predictPct[line] or server
    if drawn >= 100 then
        return
    end
    local step = ((100 - drawn) / left) * PREDICT_DAMP
    local next = drawn + step
    local ceiling = server + PREDICT_AHEAD_MAX
    if next > ceiling then
        next = ceiling
    end
    if next > 100 then
        next = 100
    end
    if next > drawn then
        predictPct[line] = next
        barsDirty = true
        -- And SAY so, on the press rather than on the per cent.
        --
        -- The strip already moved -- but one cast of Lightning Bolt is 0.57% of its rank, which on
        -- a 34-pixel strip is a fifth of a pixel. Nothing can make that read as motion. The pulse
        -- was fired on crossing a whole per cent, which is every second cast at best and every
        -- fifth on a deep line, so mid-fight the bar looked dead even while it was working.
        --
        -- Armed here, it fires on every press that counted, which is the thing the reader is
        -- actually asking about: did that one count? StripStep still pulses on the per cent as
        -- well; the two coincide often and neither reads as noise at 0.45 seconds a fade.
        pulseLine[line] = true
    end
end

-- The four buttons nobody asked for.
--
-- Every Adventurer is handed Auto Shot, Pick Lock, Throw and Shoot on its first login, because it
-- may equip a bow, a wand and a thrown weapon from level one and three of the four were Blizzard's
-- gift to somebody else's class. The client makes a button for a spell it watches arrive, so a
-- brand new character's bar opened with those four on it and nothing else -- while the one ability
-- the character was actually seeded with sat in the spellbook behind them.
--
-- This cannot be fixed where it is caused. The grant has to happen on login: the core fires its
-- character-creation hook after the character has already been saved (CharacterHandler.cpp:589),
-- so there is no earlier moment to learn them in, and playercreateinfo_spell_custom rejects
-- class 10 outright. So the buttons are made and then taken off again, here.
--
-- Bounded, and armed by the SERVER rather than by a client event. Only a ClassLess character is
-- told to run it: a real Hunter wants Auto Shot on its bar and a real Rogue wants Pick Lock, so
-- arming this off PLAYER_ENTERING_WORLD would strip four classes of something they were meant to
-- have. The addon ships to everyone on this realm, so "am I a ClassLess character" is never a
-- question the client may answer for itself.
--
-- It runs for a few seconds and then stops. A permanent sweep would also undo a deliberate drag,
-- and "I put Shoot there myself" has to keep working.
local UNWANTED_ACTIONS = {
    [75] = true,    -- Auto Shot
    [1804] = true,  -- Pick Lock
    [2764] = true,  -- Throw
    [5019] = true,  -- Shoot
}
local UNWANTED_FOR = 8
local unwantedUntil = 0

local function ArmUnwantedSweep()
    unwantedUntil = (GetTime and GetTime() or 0) + UNWANTED_FOR
end

local function SweepUnwantedActions()
    if PickupAction == nil or ClearCursor == nil or GetActionInfo == nil then
        return
    end
    -- Never while the player is holding something: PickupAction would swap the two rather than
    -- discard the one, and drop whatever was on the cursor into the bar.
    if GetCursorInfo and GetCursorInfo() then
        return
    end
    if InCombatLockdown and InCombatLockdown() then
        return
    end
    for slot = 1, 120 do
        if HasAction(slot) then
            local kind, id, subType = GetActionInfo(slot)
            if kind == "spell" and id and id > 0 then
                -- 3.3.5 hands back a spell BOOK INDEX here, and only the hyperlink says the
                -- real id out loud. ActionSpell falls back to treating the index AS an id when
                -- the link cannot be read; this must NOT. A book index and a spell id are both
                -- small integers, GetSpellInfo answers for almost any of them, and a character
                -- deep enough to hold 75 spells has a book index 75 -- which is Auto Shot's id.
                -- Guessing wrong there draws a strip on the wrong button; guessing wrong HERE
                -- deletes a button the player wanted. Unreadable means left alone.
                local sid = SpellIdFromBook(id, subType)
                if sid and UNWANTED_ACTIONS[sid] then
                    PickupAction(slot)
                    ClearCursor()
                end
            end
        end
    end
end

