-- What the strips can and cannot see, printed. There is no way to run a real client from the
-- test rig, so when a strip does not appear this is the thing that says which half is wrong:
-- no buttons found, no spell on them, no line behind the spell, or no practice on the line.
local function PracticeBarsReport()
    local buttons = ActionButtons()
    Print("build |cffffd100" .. PRACTICE_BARS_BUILD .. "|r")
    Print("action buttons found: |cffffd100" .. #buttons .. "|r, strips "
        .. (barsShown and "on" or "off"))
    local shownCount, n = 0, 0
    for i = 1, #buttons do
        local btn = buttons[i]
        local spell = ActionSpell(btn)
        if spell then
            n = n + 1
            local line = actionLine[spell]
            local pct = line and practiceSkill[line]
            if pct and pct > 0 then
                shownCount = shownCount + 1
            end
            if n <= 12 then
                local name = GetSpellInfo(spell) or "?"
                -- With no line, the next question is always the same one: did we ask the server
                -- and get nothing back, or did we never ask? Answer it here rather than making
                -- the reader guess, because the two have different causes -- a server that does
                -- not know the spell, against a client that has latched the id as asked.
                local why = ""
                if line == nil then
                    local asked = actionAsked[spell]
                    if asked == nil then
                        why = " |cffff5555[never asked]|r"
                    else
                        why = string.format(" |cffff5555[asked %.0fs ago, no answer]|r",
                            ((GetTime and GetTime()) or 0) - asked)
                    end
                end
                Print("  slot " .. i .. ": " .. name .. " (spell " .. spell .. ") -> line "
                    .. tostring(line) .. ", " .. tostring(pct) .. "%" .. why)
            end
        end
    end
    Print("spells on bars: |cffffd100" .. n .. "|r, of which drawn: |cffffd100"
        .. shownCount .. "|r")
    -- And the other half. Printed when it arrives, a moment after this line.
    local ask = {}
    for i = 1, #buttons do
        local spell = ActionSpell(buttons[i])
        if spell and #ask < 6 then
            ask[#ask + 1] = spell
        end
    end
    AIO.Handle(handlerName, "PracticeProbe", table.concat(ask, ","))
end

