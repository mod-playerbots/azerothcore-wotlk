        btn.icon = btn:CreateTexture(nil, "ARTWORK")
        btn.icon:SetWidth(36)
        btn.icon:SetHeight(36)
        btn.icon:SetPoint("TOP", 0, -6)
        -- Trimmed the way every icon in this client is: the outer edge of a spell icon is border,
        -- and a raw one next to the stock frame looks a size too big.
        btn.icon:SetTexCoord(0.07, 0.93, 0.07, 0.93)
        btn.iconEdge = btn:CreateTexture(nil, "OVERLAY")
        btn.iconEdge:SetTexture("Interface\\Buttons\\UI-Quickslot2")
