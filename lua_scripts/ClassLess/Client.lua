    --
    -- There was one, with a bar that hid itself whenever the grid fitted -- and it kept coming
    -- back, because UIPanelScrollFrameTemplate re-shows its bar from OnScrollRangeChanged, which
    -- fires after anything this file does. Rather than race a template for control of a widget
    -- that should never have been visible, the scrolling is gone: the busiest ability in the game
    -- binds twenty-five talents, which is five rows, and the card is simply that tall when it
    -- needs to be. Nothing to scroll means nothing to scroll WITH.
    local inner = CreateFrame("Frame", nil, card)
    inner:SetPoint("TOPLEFT", 20, -84)
    inner:SetWidth(CHOICE_GRID_W)
    inner:SetHeight(1)
    card.inner = inner

