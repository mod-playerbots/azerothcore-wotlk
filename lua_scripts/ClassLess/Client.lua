local function InitializeClasslessBars(hasWotLK)
    if CLBarsFrame and CLBarsFrame.bars then
        return
    end

    local activeBars = {}
    for _, cfg in ipairs(RESOURCE_BARS) do
        if not cfg.requiresWotLK or hasWotLK then
            activeBars[#activeBars + 1] = cfg
        end
    end

    local BAR_HEIGHT, BAR_GAP, PADDING = 16, 4, 8
    local frameHeight = PADDING * 2 + #activeBars * BAR_HEIGHT + (#activeBars - 1) * BAR_GAP

    local frame = CLBarsFrame or CreateFrame("Frame", "CLBarsFrame", UIParent)
    frame:SetMovable(true)
    frame:EnableMouse(true)
    frame:SetToplevel(true)
    frame:RegisterForDrag("LeftButton")
    frame:SetSize(172, frameHeight)
    frame:SetBackdrop({
        bgFile = "",
        edgeFile = "",
        tile = true,
        edgeSize = 16,
        tileSize = 32,
        insets = {left = 5, right = 5, top = 5, bottom = 5}
    })
    frame:SetPoint("CENTER", 0, 0)
    frame:SetScript("OnDragStart", frame.StartMoving)
    frame:SetScript("OnDragStop", frame.StopMovingOrSizing)

    AIO.SavePosition(frame)

    local bars = {}
    for i, cfg in ipairs(activeBars) do
        local bar = CreateFrame("StatusBar", nil, frame)
        bar:SetPoint("TOPLEFT", PADDING, -PADDING - (i - 1) * (BAR_HEIGHT + BAR_GAP))
        bar:SetWidth(116)
        bar:SetHeight(BAR_HEIGHT)
        bar:SetStatusBarTexture("Interface\\TARGETINGFRAME\\UI-StatusBar")
        bar:GetStatusBarTexture():SetHorizTile(false)
        bar:GetStatusBarTexture():SetVertTile(false)
        bar:SetStatusBarColor(cfg.r, cfg.g, cfg.b)

        bar.bg = bar:CreateTexture(nil, "BACKGROUND")
        bar.bg:SetTexture("Interface\\TARGETINGFRAME\\UI-StatusBar")
        bar.bg:SetAllPoints(true)
        bar.bg:SetVertexColor(0, 0, 0)

        bar.value = bar:CreateFontString(nil, "OVERLAY")
        bar.value:SetPoint("CENTER")
        bar.value:SetFont("Fonts\\FRIZQT__.TTF", 12, "OUTLINE")
        bar.value:SetJustifyH("CENTER")
        bar.value:SetShadowOffset(1, -1)
        bar.value:SetTextColor(1, 1, 1)

        -- "OnUpdate", not "Onupdate": script handler names are case-sensitive, so the typo
        -- silently registered nothing and the original (Rage-only) bar never updated -- it
        -- sat empty because SetMinMaxValues/SetValue are only ever called in here.
        bar:SetScript("OnUpdate", function()
            -- A bar for the power this character already SHOWS is two of the same thing. The
            -- Adventurer runs on mana, so its Energy and Rage live only here; a real Rogue has
            -- Energy under its portrait already and does not need it twice.
            if UnitPowerType("player") == cfg.power then
                bar:Hide()
                return
            end
            bar:Show()
            local pw = UnitPower("player", cfg.power) or 0
            local pwm = UnitPowerMax("player", cfg.power) or 100
            bar:SetMinMaxValues(0, pwm)
            bar:SetValue(pw)
            bar.value:SetText(pw .. "/" .. pwm)
        end)

        bars[i] = bar
    end

    frame.bars = bars
end

