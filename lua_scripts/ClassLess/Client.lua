end

local function CreateCollFrame()
    local f = CreateFrame("Frame", "CLCollectionFrame", UIParent)
    -- 820 wide, not 780. FauxScrollFrameTemplate hangs its slider off the scroll frame's right
    -- edge (anchored TOPLEFT to TOPRIGHT at x = -2, and the slider is 16 wide), so the bar
    -- lives almost entirely outside the frame it belongs to. Both panes have to leave that
    -- much clear or the left one's bar is drawn across the right one's border.
    f:SetSize(820, 520)
    f:SetPoint("CENTER")
    f:SetMovable(true)
    f:EnableMouse(true)
    f:SetToplevel(true)
    f:RegisterForDrag("LeftButton")
    f:SetScript("OnDragStart", f.StartMoving)
    f:SetScript("OnDragStop", f.StopMovingOrSizing)
    f:SetBackdrop({
        bgFile = "Interface\\DialogFrame\\UI-DialogBox-Background",
        edgeFile = "Interface\\DialogFrame\\UI-DialogBox-Border",
        tile = true, tileSize = 32, edgeSize = 32,
        insets = {left = 11, right = 12, top = 12, bottom = 11},
    })
    f:SetFrameStrata("HIGH")
    -- Escape closes it, same as every stock panel.
    tinsert(UISpecialFrames, "CLCollectionFrame")

    local title = f:CreateFontString(nil, "OVERLAY", "GameFontNormalLarge")
    title:SetPoint("TOP", 0, -16)
    title:SetText("Tome Collection")

    f.progress = f:CreateFontString(nil, "OVERLAY", "GameFontNormalSmall")
    f.progress:SetPoint("TOPRIGHT", -40, -20)

    local close = CreateFrame("Button", nil, f, "UIPanelCloseButton")
    close:SetPoint("TOPRIGHT", -8, -8)

    -- Search --------------------------------------------------------------------------
    local search = CreateFrame("EditBox", "CLCollectionSearch", f, "InputBoxTemplate")
    search:SetSize(240, 20)
    search:SetPoint("TOPLEFT", 248, -48)
    search:SetAutoFocus(false)
    search:SetScript("OnTextChanged", function(self)
        searchText = self:GetText() or ""
        BuildView()
        FauxScrollFrame_SetOffset(f.listScroll, 0)
        local sb = _G["CLCollectionListScrollScrollBar"]
        if sb then sb:SetValue(0) end
        RefreshList()
    end)
    search:SetScript("OnEscapePressed", function(self)
        self:SetText("")
        self:ClearFocus()
    end)
    local searchLabel = f:CreateFontString(nil, "OVERLAY", "GameFontNormalSmall")
    searchLabel:SetPoint("RIGHT", search, "LEFT", -6, 0)
    searchLabel:SetText("Search")

    f.missing = CreateFrame("CheckButton", "CLCollectionMissing", f, "UICheckButtonTemplate")
    f.missing:SetSize(22, 22)
    f.missing:SetPoint("LEFT", search, "RIGHT", 12, 0)
    _G["CLCollectionMissingText"]:SetText("Only what I am missing")
    f.missing:SetScript("OnClick", function()
        BuildView()
        RefreshList()
    end)

    -- Left column: class > spec ---------------------------------------------------------
    f.navScroll = CreateFrame("ScrollFrame", "CLCollectionNavScroll", f,
        "FauxScrollFrameTemplate")
    f.navScroll:SetSize(184, NAV_ROWS * NAV_ROW_H)
    f.navScroll:SetPoint("TOPLEFT", 20, -76)
    f.navScroll:SetScript("OnVerticalScroll", function(self, offset)
        FauxScrollFrame_OnVerticalScroll(self, offset, NAV_ROW_H, RefreshNav)
    end)

    local function Inset(anchor, w, h)
        local inset = CreateFrame("Frame", nil, f)
        inset:SetPoint("TOPLEFT", anchor, "TOPLEFT", -6, 6)
        inset:SetSize(w, h)
        inset:SetBackdrop({
            bgFile = "Interface\\ChatFrame\\ChatFrameBackground",
            edgeFile = "Interface\\Tooltips\\UI-Tooltip-Border",
            tile = true, tileSize = 16, edgeSize = 12,
            insets = {left = 3, right = 3, top = 3, bottom = 3},
        })
        inset:SetBackdropColor(0, 0, 0, 0.35)
        inset:SetBackdropBorderColor(0.4, 0.4, 0.4, 0.7)
        -- Children default to the parent's frame level + 1, which is also where the row
        -- buttons sit; without this the inset and the rows fight over who draws on top.
        inset:SetFrameLevel(f:GetFrameLevel())
        return inset
    end
    Inset(f.navScroll, 210, NAV_ROWS * NAV_ROW_H + 12)

    f.navRows = {}
    for i = 1, NAV_ROWS do
        local btn = MakeRow(f, NAV_ROW_H, 168)
        btn:SetPoint("TOPLEFT", f.navScroll, "TOPLEFT", 0, -(i - 1) * NAV_ROW_H)
        btn.icon:SetSize(14, 14)
        btn.icon:SetPoint("LEFT", 10, 0)
        btn.state:Hide()
        btn.bar:Hide()
        btn.level:SetText("")
        btn.count:SetPoint("RIGHT", -4, 0)
        btn.text:SetPoint("RIGHT", -40, 0)
        -- Which spec is being shown. Text colour alone is not enough to find at a glance in
        -- a list of sixty rows.
        btn.sel = btn:CreateTexture(nil, "BACKGROUND")
        btn.sel:SetTexture("Interface\\QuestFrame\\UI-QuestTitleHighlight")
        btn.sel:SetAllPoints(btn)
        btn.sel:SetVertexColor(0.4, 0.5, 0.7)
        btn.sel:Hide()
        btn:SetScript("OnClick", function(self)
            local item = self.item
            if item == nil then return end
            if item.zones then
                zonesCollapsed = not zonesCollapsed
                if not zonesCollapsed and #zoneList == 0 then
                    AIO.Handle(handlerName, "CollZones")
                end
                BuildNav()
                RefreshNav()
            elseif item.zone then
                local zone = zoneList[item.zone][1]
                selectedZone, selectedPage = zone, nil
                searchText = ""
                search:SetText("")
                if zoneRows[zone] == nil and not zonePending[zone] then
                    zonePending[zone] = true
                    AIO.Handle(handlerName, "CollZone", zone)
                end
                BuildView()
                FauxScrollFrame_SetOffset(f.listScroll, 0)
                local sb = _G["CLCollectionListScrollScrollBar"]
                if sb then sb:SetValue(0) end
                RefreshNav()
                RefreshList()
            elseif item.header then
                navCollapsed[item.cls] = not navCollapsed[item.cls]
                BuildNav()
                RefreshNav()
            else
                selectedPage, selectedZone = item.page, nil
                searchText = ""
                search:SetText("")
                BuildView()
                FauxScrollFrame_SetOffset(f.listScroll, 0)
                local sb = _G["CLCollectionListScrollScrollBar"]
        if sb then sb:SetValue(0) end
                RefreshNav()
                RefreshList()
            end
        end)
        f.navRows[i] = btn
    end

    -- Right column: lines, and the ranks of an expanded line ----------------------------
    f.listScroll = CreateFrame("ScrollFrame", "CLCollectionListScroll", f,
        "FauxScrollFrameTemplate")
    f.listScroll:SetSize(538, LIST_ROWS * LIST_ROW_H)
    f.listScroll:SetPoint("TOPLEFT", 242, -76)
    f.listScroll:SetScript("OnVerticalScroll", function(self, offset)
        FauxScrollFrame_OnVerticalScroll(self, offset, LIST_ROW_H, RefreshList)
    end)

    Inset(f.listScroll, 564, LIST_ROWS * LIST_ROW_H + 12)

    f.listRows = {}
    for i = 1, LIST_ROWS do
        local btn = MakeRow(f, LIST_ROW_H, 522)
        btn:SetPoint("TOPLEFT", f.listScroll, "TOPLEFT", 0, -(i - 1) * LIST_ROW_H)
        btn:SetScript("OnClick", function(self)
            local item = self.item
            if item == nil or item.row then return end
            if item.opt then
                -- Clicking a choice that has not been earned yet is not an error, it is a
                -- misread of the row: say nothing and leave the offer standing.
                if not offerReady[item.line.id] then
                    return
                end
                -- The server re-derives the options before it charges anything, so a stale
                -- panel cannot take something that is no longer on the table.
                AIO.Handle(handlerName, "PracticePick", item.line.id, item.opt.rank)
                offerOf[item.line.id] = nil
                BuildView()
                RefreshList()
                return
            end
            local id = item.line.id
            if expanded[id] then
                expanded[id] = nil
            else
                expanded[id] = true
                RequestLine(id)
                -- Ask what this line could spend even if no offer has been pushed: the reader
                -- may be opening it to see how far off the next rank is.
                AIO.Handle(handlerName, "PracticeAsk", id)
            end
            BuildView()
            RefreshList()
        end)
        btn:SetScript("OnEnter", function(self)
            local item = self.item
            if item == nil then return end
            if item.opt then
                GameTooltip:SetOwner(self, "ANCHOR_RIGHT")
                GameTooltip:AddLine(SpellName(item.opt.from or item.opt.rank), 1, 1, 1)
                GameTooltip:AddLine("Costs one advance of " .. SpellName(item.line.id)
                    .. ((offerNeed[item.line.id] and offerNeed[item.line.id] > 0)
                        and (" -- about " .. offerNeed[item.line.id] .. " presses of it")
                        or ""), 0.8, 0.8, 0.8)
                if item.opt.from ~= item.line.id then
                    GameTooltip:AddLine("A talent that improves "
                        .. SpellName(item.line.id) .. ".", 0.6, 0.8, 0.6)
                end
                GameTooltip:AddLine(" ")
                GameTooltip:AddLine("Click to spend the practice on this.", 0.5, 0.7, 1)
                GameTooltip:AddLine("The practice pays for ONE of the choices.", 1, 0.5, 0.2)
                GameTooltip:AddLine("Leave it unanswered and the next rank is taken for you.",
                                    0.7, 0.7, 0.7, true)
                GameTooltip:Show()
            elseif item.row then
                ShowRankTooltip(self, item.line, item.row)
            else
                GameTooltip:SetOwner(self, "ANCHOR_RIGHT")
                GameTooltip:AddLine(SpellName(item.line.id), 1, 1, 1)
                GameTooltip:AddLine(item.line.owned .. " of " .. item.line.total
                    .. " ranks found", 0.8, 0.8, 0.8)
                GameTooltip:AddLine("Opens at level " .. item.line.level, 0.6, 0.6, 0.6)
                if item.line.rare then
                    GameTooltip:AddLine("Boss drop only, binds on pickup.", 1, 0.5, 0.2)
                end
                local banked = practiceLine[item.line.id]
                if banked and banked > 0 then
                    GameTooltip:AddLine("Practice banked: " .. banked, 0.4, 0.9, 0.4)
                end
                GameTooltip:AddLine(" ")
                GameTooltip:AddLine("Click to see each rank and where it drops.",
                    0.5, 0.7, 1)
                GameTooltip:Show()
            end
        end)
        btn:SetScript("OnLeave", function() GameTooltip:Hide() end)
        f.listRows[i] = btn
    end

    f.status = f:CreateFontString(nil, "OVERLAY", "GameFontNormalSmall")
    f.status:SetPoint("BOTTOMLEFT", 24, 22)
    f.status:SetPoint("BOTTOMRIGHT", -24, 22)
    f.status:SetJustifyH("LEFT")
    f.status:SetTextColor(0.6, 0.6, 0.6)

    AIO.SavePosition(f)
    -- CreateFrame returns a SHOWN frame, so without this the first /tomes would create the
    -- panel and the toggle below would read it as already open and close it again.
    f:Hide()
    return f
end

-- ---------------------------------------------------------------------------------------
-- The choice prompt.
--
-- Dressed to match the Paragon frames this realm already ships, because a panel that looks like
-- somebody's addon reads as somebody's addon. The palette and the art are lifted from
-- Interface/FrameXML/Paragon/UIParagon.xml rather than invented: the gold is the 0.90/0.80/0.50 its
-- headings use, the ground is the stone panel behind its statistics page, and the flame strip under
-- the title is the same texture it puts under its own. All of it is already in Patch-Z, so this
-- addon -- which ships as bare Lua over AIO and carries no art of its own -- can name the files.
-- ---------------------------------------------------------------------------------------
-- A grid, not a column.
--
-- Seventeen talents bind to Lightning Bolt and twenty-five to the busiest line in the game; as
-- rows that is a scroll bar and three screenfuls, and the question the panel exists to answer --
-- "what can this ability become" -- is one you answer by looking at the whole set at once. Five
-- across covers the worst case in five rows, so nothing ever scrolls in practice and the scroll
-- frame is left in only as a floor under a number that grows later.
local CHOICE_COLS = 5
local CHOICE_CELL_W = 98
local CHOICE_CELL_H = 94
-- Space BETWEEN cells, not inside them. The cells used to be laid out at their own width, edge to
-- edge, so the only thing separating two icons was the padding each drew around itself -- and a
-- highlight on hover then touched its neighbours. The pitch carries the gap and the cell keeps its
-- size, which is what stops the icons shrinking every time the grid is loosened.
local CHOICE_GAP = 5
local CHOICE_PITCH_W = CHOICE_CELL_W + CHOICE_GAP
local CHOICE_PITCH_H = CHOICE_CELL_H + CHOICE_GAP
local CHOICE_GRID_W = CHOICE_COLS * CHOICE_CELL_W + (CHOICE_COLS - 1) * CHOICE_GAP
local CHOICE_W = 20 + CHOICE_GRID_W + 20

local PARA_GOLD = {0.90, 0.80, 0.50}
local PARA_STONE = "Interface\\Housing\\housingbasicpanelstonebackground2x"
local PARA_EDGE = "Interface\\DialogFrame\\UI-DialogBox-Gold-Border"

-- Manual lerps on OnUpdate rather than an AnimationGroup.
--
-- 3.3.5 does have animation groups, and Paragon_Animations.lua does not use them either: it runs
-- everything off GetTime() deltas. Matching that is worth more than the tidier API -- one style of
-- motion across the realm's frames, and no chance of an animation still running after the frame it
-- belongs to has gone.
local CHOICE_FADE = 0.22
local CHOICE_RISE = 26              -- pixels the card travels up on the way in

local function ChoiceAnimate(f, dir)
    f.animDir, f.animStart = dir, GetTime()
    if dir == "in" then
        f:Show()
        f:SetAlpha(0)
    end
end

local function ChoiceAnimStep(f)
    if f.animDir == nil then
        return
    end
    local t = (GetTime() - f.animStart) / CHOICE_FADE
    if t > 1 then
        t = 1
    end
    -- Ease out. Linear reads as a slide; this reads as something arriving and settling.
    local e = 1 - (1 - t) * (1 - t)
    if f.animDir == "in" then
        f:SetAlpha(e)
        f.card:SetPoint("CENTER", f, "CENTER", 0, 40 - CHOICE_RISE * (1 - e))
        if t >= 1 then
            f.animDir = nil
        end
    else
        f:SetAlpha(1 - e)
        f.card:SetPoint("CENTER", f, "CENTER", 0, 40 + (CHOICE_RISE * 0.5) * e)
        if t >= 1 then
            f.animDir = nil
            f:Hide()
            f:SetAlpha(1)
        end
    end
end

local function CreateChoiceFrame()
    local f = CreateFrame("Frame", "CLChoiceFrame", UIParent)
    f:SetAllPoints(UIParent)
    -- Above everything, including the collection panel, which sits at HIGH.
    f:SetFrameStrata("FULLSCREEN_DIALOG")
    -- A faint dim behind it, and the mouse left alone.
    --
    -- These were one thing and are now two. The first version dimmed the screen to 0.7 AND
    -- swallowed every click, so the world went dark and stopped answering at the same moment; the
    -- second dropped both, which left the panel floating on a lit screen with nothing setting it
    -- apart. What was actually wrong was the blocking, not the shading -- so the shading comes
    -- back at half the weight and EnableMouse stays off. Click straight through it to whatever is
    -- behind; the card has its own mouse and the world keeps its.
    --
    -- A texture rather than a backdrop: backdrops do not tile to an arbitrary resolution.
    f.dim = f:CreateTexture(nil, "BACKGROUND")
    f.dim:SetAllPoints(f)
    f.dim:SetTexture(0, 0, 0, 0.35)
    f:EnableMouse(false)
    f:SetToplevel(true)
    f:SetScript("OnUpdate", function(self) ChoiceAnimStep(self) end)

    local card = CreateFrame("Frame", nil, f)
    card:SetPoint("CENTER", f, "CENTER", 0, 40)
    card:SetWidth(CHOICE_W)
    card:EnableMouse(true)          -- clicks on the card are the card's, not the world's
    -- The border through the backdrop, the GROUND as our own textures.
    --
    -- bgFile alone was see-through: the stone panel is a 2x art file with its own alpha, and a
    -- backdrop draws it once at whatever the frame's colour says -- so the card came up as a gold
    -- frame around the cobblestones, with the character model visible through the rows. Two
    -- layers fix it and neither depends on that file's alpha: a flat opaque black first, the stone
    -- over it for the texture. If the stone ever fails to load, the card is merely plain.
    card:SetBackdrop({
        edgeFile = PARA_EDGE,
        edgeSize = 32,
        insets = { left = 11, right = 12, top = 12, bottom = 11 },
    })
    card.ground = card:CreateTexture(nil, "BACKGROUND")
    card.ground:SetTexture(0.04, 0.04, 0.05, 0.96)
    card.ground:SetPoint("TOPLEFT", 11, -12)
    card.ground:SetPoint("BOTTOMRIGHT", -12, 11)
    card.stone = card:CreateTexture(nil, "BACKGROUND")
    card.stone:SetTexture(PARA_STONE)
    card.stone:SetPoint("TOPLEFT", 11, -12)
    card.stone:SetPoint("BOTTOMRIGHT", -12, 11)
    card.stone:SetAlpha(0.55)
    f.card = card

    -- FRIZQT at 20 rather than GameFontNormalLarge, which is the same face two sizes down. Made
    -- here instead of named, because a font object this addon does not ship cannot be relied on.
    if CLParagonTitleFont == nil then
        CLParagonTitleFont = CreateFont("CLParagonTitleFont")
        CLParagonTitleFont:SetFont("Fonts\\FRIZQT__.ttf", 20)
        CLParagonTitleFont:SetShadowOffset(1, -1)
        CLParagonTitleFont:SetShadowColor(0, 0, 0, 1)
    end
    -- The ability itself is the heading: its icon and its name.
    --
    -- It used to say "Practice earned", which named the mechanic rather than the subject -- and
    -- the subject then had to be repeated in the sentence underneath, where it was the first thing
    -- to run out of room. A panel about Lightning Bolt should say Lightning Bolt at the top, with
    -- the icon the reader clicks on their bar, so there is no moment of working out what they are
    -- looking at.
    --
    -- Nudged right by half the icon's width so that the icon and the name read as one centred
    -- group rather than a centred name with something hanging off its left.
    card.title = card:CreateFontString(nil, "OVERLAY")
    card.title:SetFontObject(CLParagonTitleFont)
    card.title:SetPoint("TOP", 22, -24)
    card.title:SetTextColor(PARA_GOLD[1], PARA_GOLD[2], PARA_GOLD[3])

    card.titleIcon = card:CreateTexture(nil, "ARTWORK")
    card.titleIcon:SetWidth(32)
    card.titleIcon:SetHeight(32)
    card.titleIcon:SetPoint("RIGHT", card.title, "LEFT", -8, -1)
    card.titleIcon:SetTexCoord(0.07, 0.93, 0.07, 0.93)
    card.titleEdge = card:CreateTexture(nil, "OVERLAY")
    card.titleEdge:SetTexture("Interface\\Buttons\\UI-Quickslot2")
    card.titleEdge:SetWidth(58)
    card.titleEdge:SetHeight(58)
    card.titleEdge:SetPoint("CENTER", card.titleIcon, "CENTER", 0, -1)
    card.titleEdge:SetAlpha(0.7)

    -- A rule under the heading, drawn rather than borrowed.
    --
    -- This was PARA_FLAME stretched across the card, and it came out as a torn smear on the right
    -- -- because TheWarWithinMajorFactionsFlame is an ATLAS. Every use of it in UIParagon.xml cuts
    -- a slice with TexCoords; drawing the whole file means drawing several unrelated pieces of art
    -- at once. Guessing at the right slice is how the last two art problems today started, so
    -- there is no file here at all: two solid textures meeting in the middle, each fading out
    -- towards its end. Same gold, and it cannot render wrong.
    local function rule(side, toward)
        local t = card:CreateTexture(nil, "ARTWORK")
        t:SetTexture(1, 1, 1, 1)
        t:SetHeight(2)
        t:SetPoint("TOP" .. side, card, "TOP" .. side, (side == "LEFT") and 30 or -30, -64)
        t:SetPoint("TOP" .. toward, card, "TOP", 0, -64)
        -- Transparent at the outside edge, solid where the two meet.
        pcall(t.SetGradientAlpha, t, "HORIZONTAL",
            PARA_GOLD[1], PARA_GOLD[2], PARA_GOLD[3], (side == "LEFT") and 0 or 0.9,
            PARA_GOLD[1], PARA_GOLD[2], PARA_GOLD[3], (side == "LEFT") and 0.9 or 0)
        return t
    end
    card.ruleL = rule("LEFT", "RIGHT")
    card.ruleR = rule("RIGHT", "LEFT")

    -- The heading answers for itself.
    --
    -- Two lines of prose used to sit under it -- what the panel was for, and how many casts were
    -- left -- and they were the only text on the card nobody had asked a question to get. The
    -- ability is named at the top and every cell below is a talent; that is the sentence. What is
    -- worth keeping is the cast count, and a number about Lightning Bolt belongs on Lightning
    -- Bolt: hovering the heading gives the game's own spell tooltip with the practice underneath.
    local hot = CreateFrame("Frame", nil, card)
    hot:SetPoint("TOPLEFT", card.titleIcon, "TOPLEFT", -4, 4)
