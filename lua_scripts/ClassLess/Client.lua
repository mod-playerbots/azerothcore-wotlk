                     "UPDATE_SHAPESHIFT_FORM", "LEARNED_SPELL_IN_TAB", "SPELLS_CHANGED",
                     "UPDATE_BONUS_ACTIONBAR"}) do
    pcall(barWatcher.RegisterEvent, barWatcher, ev)
end
pcall(barWatcher.RegisterEvent, barWatcher, "UNIT_SPELLCAST_SUCCEEDED")
barWatcher:SetScript("OnEvent", function(self, event, unit, spellName)
    if event == "UNIT_SPELLCAST_SUCCEEDED" then
        -- Named rather than identified, and matched by name on purpose: every rank of a line
        -- shares one, which is the granularity practice works at. The player only -- a pet's
        -- casts are its own.
        if unit == "player" and spellName then
            local line = nameLine[spellName]
            if line then
                PracticePredictPress(line)
            end
        end
        return
    end
    -- The button frames of a replacement bar addon may not exist yet at PLAYER_ENTERING_WORLD,
    -- so the list is dropped and rebuilt rather than cached from the first look.
    barButtons = nil
    barsDirty = true
end)
-- And a sweep every couple of seconds whether or not anything fired.
--
-- Events are not enough to rely on here and the failure is silent when they are missed: the
-- buttons of a replacement bar addon appear after ours does, the practice data arrives from the
-- server on its own schedule, and PLAYER_ENTERING_WORLD can land before either. A scan of sixty
-- buttons is nothing next to being wrong for a whole session. AskForUnknown asks once per id, so
-- the sweep does not talk to the server after the first pass.
local BARS_SWEEP = 2
local talentReady = false
barWatcher:SetScript("OnUpdate", function(self, elapsed)
    elapsed = elapsed or 0
    barsClock = barsClock + elapsed
    if barsDirty or barsClock >= BARS_SWEEP then
        barsDirty, barsClock = false, 0
        PracticeBarsRefresh()
        -- Same sweep, same reason: the micro buttons may not exist yet when this file loads.
        if not talentReady then
            talentReady = RestoreTalentUI()
        end
        if (GetTime and GetTime() or 0) < unwantedUntil then
            SweepUnwantedActions()
        end
    end
    -- Every frame, unlike the sweep: this is the animation, and it walks only the buttons that
    -- actually carry a strip.
    StripStep(elapsed)
end)

-- The same progress, in the tooltip.
--
-- The strip under an icon answers "how far along is this" at a glance and nothing more precisely
-- than that -- one Fireball moves it a quarter of a pixel. The number belongs somewhere it can be
-- read, and the tooltip is where a player already looks to ask about an ability. It is also the
-- only place the spellbook can show it: a spell that is on no action bar has no strip at all.
--
-- Hooked rather than replaced. hooksecurefunc runs after the game has filled the tooltip, so the
-- practice line lands under Blizzard's own text and nothing of theirs is lost. SetAction and
-- SetSpellBookItem are the two doors that matter (a bar button and the spellbook); SetHyperlink
-- catches a spell link in chat where the client has one.
local PRACTICE_TIP_COLOR = {0.4, 0.88, 0.4}

local function TooltipPractice(tt, spellId)
    if classLessOff or spellId == nil or tt == nil or not tt.AddLine then
        return
    end
    -- A panel in this file is building this tooltip and will say it better. See tipOwn.
    if tipOwn then
        return
    end
    local line = actionLine[spellId]
    if line == nil then
        -- Never seen this id. Ask once, so the NEXT hover can answer -- the reply cannot be
        -- waited for here and redrawing a tooltip from under the cursor would flicker.
        AskForUnknown({spellId})
        return
    end
    -- Before the per cent is even looked up: a line that ranks up on the level has no per cent
    -- worth quoting, and the sentence is the same whether or not the character has practised it.
    if autoRankLine[line] then
        tt:AddLine("Automatic rank up on level up", 0.25, 0.63, 1)
        tt:Show()
        return
    end
    local pct = predictPct[line] or practiceSkill[line]
    if pct == nil then
        return
    end
    -- The cast count was in here too and came back out. "~84 more casts" is an estimate of an
    -- estimate -- it moves with the line's own cast weighting and with anything that touches the
    -- practice rate -- and putting a second number next to the first one invites reading it as a
    -- promise. The per cent is the thing being asked about.
    local left = practiceNeed[line]
    local text
    if holdLevel[line] then
        -- Full and waiting. "Completed" on its own reads as an ending, and this is not one: the
        -- bar has stopped because the next rank needs a level, not because there is nothing left
        -- to do. Naming the level is the difference between a wall and a date.
        text = string.format("Practice: %d%% completed - rank up at level %d",
            math.floor(pct), holdLevel[line])
    elseif left and left > 0 then
        text = string.format("Practice: %d%% of the next rank completed", math.floor(pct))
    else
        -- Nothing further to reach on this line, so there is no "next rank" to be a share of.
        text = string.format("Practice: %d%% completed", math.floor(pct))
    end
    tt:AddLine(text, PRACTICE_TIP_COLOR[1], PRACTICE_TIP_COLOR[2], PRACTICE_TIP_COLOR[3])
    tt:Show()
end

if hooksecurefunc and GameTooltip then
    if GameTooltip.SetAction then
        hooksecurefunc(GameTooltip, "SetAction", function(tt, slot)
            if slot == nil or not HasAction(slot) then
                return
            end
            local kind, id, subType = GetActionInfo(slot)
            if kind ~= "spell" or not id or id <= 0 then
                return
            end
            -- GetActionInfo hands back a spell BOOK INDEX, not an id. Same two-step as ActionSpell.
            local sid = SpellIdFromBook(id, subType)
            if sid == nil and GetSpellInfo(id) then
                sid = id
            end
            TooltipPractice(tt, sid)
        end)
    end
    if GameTooltip.SetSpellBookItem then
        hooksecurefunc(GameTooltip, "SetSpellBookItem", function(tt, index, book)
            TooltipPractice(tt, SpellIdFromBook(index, book))
        end)
    end
    if GameTooltip.SetHyperlink then
        hooksecurefunc(GameTooltip, "SetHyperlink", function(tt, link)
            if type(link) == "string" then
                TooltipPractice(tt, tonumber(string.match(link, "spell:(%d+)")))
            end
        end)
    end
end

