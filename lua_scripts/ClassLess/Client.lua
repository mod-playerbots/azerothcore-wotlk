-- Pushed when a rank is unlocked, so an open panel does not have to re-request the whole
-- index, and a closed one is still right the next time it opens.
function MyHandlers.CollBump(player, lineId, owned, total)
    local entry = lineOf[lineId]
    if entry == nil then
        return
    end
    local delta = (owned or 0) - entry.owned
    entry.owned, entry.total = owned or 0, total or entry.total
    stats.owned = stats.owned + delta
    local page = pages[entry.page]
    if page then
        page.owned = page.owned + delta
    end
    -- The cached rank rows carry a state per rank that this message does not repeat, so drop
    -- them rather than show a rank as missing that was just found.
    rankCache[lineId] = nil
    if CollFrame and CollFrame:IsShown() then
        UpdateHeader()
        if expanded[lineId] then
            RequestLine(lineId)
        end
        BuildView()
        RefreshNav()
        RefreshList()
    end
end

-- Pushed by the server as each rank is unlocked. Announcing it matters: the tome is read
-- from the bags with no window open, so without this the only feedback would be noticing a
-- new spell in the spellbook later.
--
-- A tome can be read at any time, so reading one does not always mean casting one. The
-- server sends what actually happened -- the client cannot work it out, because it no longer
-- carries tomes.data and cannot see the pool:
--
--   "ok"  -- learned, it is in the spellbook now
--   "lvl" -- banked; arg is the level it becomes usable at
--   "req" -- banked; arg is the rank BELOW it, which has not been found yet. Ranks are
--            collected in whatever order the world hands them over, so this is common.
--
-- Either way the rank is kept: it is released automatically the moment the blocker clears.
function MyHandlers.PoolAdd(player, sid, state, arg, src)
    if sid == nil then
        return
    end
    local name, rank = GetSpellInfo(sid)
    if name == nil then
        return
    end
    local full = name
    if rank and rank ~= "" then
        full = name .. " (" .. rank .. ")"
    end

    -- Earned by practising it, or found in the world. The two are the same event to the pool and
    -- a different one to the reader: below level 10 a full practice bar buys a rank that cannot be
    -- used yet, so this sentence is the ONLY thing the player gets for it -- and it used to say
    -- "found", next to a bar that had just restarted at zero.
    local got = (src == "practice") and "Your practice has earned "
        or "You have found "
    if state == "lvl" then
        Print(got .. "|cffffd100" .. full .. "|r. It becomes usable at level "
            .. tostring(arg) .. ".")
    elseif state == "req" then
        local prev = "the rank below it"
        if arg then
            local pn, pr = GetSpellInfo(arg)
            if pn then
                prev = pn .. ((pr and pr ~= "") and (" (" .. pr .. ")") or "")
            end
        end
        Print(got .. "|cffffd100" .. full .. "|r, but you must learn |cffffd100"
            .. prev .. "|r first. It is kept until you do.")
    else
        -- The rank landed and is usable NOW. Said in the game's own SKILL colour rather than as a
        -- tagged [ClassLess] line, on the user's call of 2026-09-19: this is the same kind of
        -- event the game already announces that way, and in that colour it reads as part of the
        -- game instead of as an addon talking over it.
        --
        -- Where it came from is still in the sentence. "Increased to" is the practice route --
        -- the ability itself got better by being used -- and "learned" is the one that came off a
        -- corpse, which is a different thing that happened to produce the same rank.
        if src == "practice" and rank and rank ~= "" then
            SkillUp("Your " .. name .. " has increased to " .. rank .. ".")
        elseif src == "practice" then
            SkillUp("Your " .. name .. " has improved.")
        else
            SkillUp("You have learned " .. full .. ".")
        end
        -- ...and light the button it is sitting on. Flagged here and drawn by the action-bar
        -- pass, which is what owns the buttons; see rankGlow.
        rankGlow[name] = true
        if WakeBars then
            WakeBars()
        end
    end
end

