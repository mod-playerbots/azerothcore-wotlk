        local line = f.lineId
        if line == nil then
            return
        end
        -- Above the heading. ANCHOR_BOTTOM dropped it straight down over the grid, hiding the
        -- talents while the reader was looking at the thing they all belong to.
        GameTooltip:SetOwner(self, "ANCHOR_TOP")
        tipOwn = true
        local ok = pcall(GameTooltip.SetHyperlink, GameTooltip, "spell:" .. line)
        tipOwn = false
        if not ok then
            GameTooltip:Hide()
            return
        end
        -- practiceSkill only, not the predicted value: predictPct is declared with the action-bar
        -- strips, hundreds of lines BELOW this one, so up here the name is a nil global and
        -- indexing it is an error rather than a fallback. The server-confirmed number is the right
        -- one for a tooltip anyway -- a tooltip is read, not watched.
        local pct = practiceSkill[line]
        if autoRankLine[line] then
            GameTooltip:AddLine(" ")
            GameTooltip:AddLine("Automatic rank up on level up", 0.25, 0.63, 1)
        elseif pct then
            GameTooltip:AddLine(" ")
            GameTooltip:AddLine(string.format("Practice: %d%% of the next rank completed",
                math.floor(pct)), 0.4, 0.88, 0.4)
        end
        local need = offerNeed[line]
        if need and need > 0 then
            if pct == nil then
                GameTooltip:AddLine(" ")
            end
            GameTooltip:AddLine("About " .. need .. " more casts to the next advance.",
                0.7, 0.7, 0.7)
        end
        GameTooltip:Show()
    end)
    hot:SetScript("OnLeave", function() GameTooltip:Hide() end)
    card.hot = hot

