    GameTooltip:SetOwner(owner, "ANCHOR_RIGHT")
    local itemId = row[R_ITEM] or 0
    -- The real item tooltip when the client has the item cached (it carries the binding and
    -- the vendor price, which is the honest answer to "can I just buy this"); our own header
    -- when it does not, because SetHyperlink on an uncached item draws an empty box.
    if itemId > 0 and GetItemInfo(itemId) then
        GameTooltip:SetHyperlink("item:" .. itemId .. ":0:0:0:0:0:0:0:0")
        GameTooltip:AddLine(" ")
    else
        local name, rank = GetSpellInfo(row[R_ID])
        GameTooltip:AddLine(name or SpellName(row[R_ID]), 1, 1, 1)
        if rank and rank ~= "" then
            GameTooltip:AddLine(rank, 0.6, 0.6, 0.6)
        end
    end

    local state = row[R_STATE]
    if state == STATE_LEARNED then
        GameTooltip:AddLine("Learned.", 0.25, 0.75, 0.25)
    elseif state == STATE_BANKED then
        GameTooltip:AddLine("Found, but not usable yet.", 1, 0.82, 0)
        GameTooltip:AddLine("Needs level " .. row[R_LEVEL]
            .. ", and the rank below it.", 0.8, 0.8, 0.8, true)
    else
        GameTooltip:AddLine("Not found.", 0.8, 0.3, 0.3)
        GameTooltip:AddLine("Usable at level " .. row[R_LEVEL] .. ".", 0.8, 0.8, 0.8)
    end

    GameTooltip:AddLine(" ")
    GameTooltip:AddLine("Found on:", 1, 1, 1)
    local kind = row[R_KIND]
    if kind == "l" then
        GameTooltip:AddLine("  nowhere -- this rank arrives when you reach level "
            .. tostring(row[R_LEVEL]), 0.25, 0.63, 1)
        GameTooltip:AddLine("A buff, stance or teleport is pressed once and then lived with, so "
            .. "there is nothing to practise. Find the first rank and the rest follow you up.",
            0.8, 0.8, 0.8, true)
    elseif kind == "p" then
        GameTooltip:AddLine("  nowhere -- this rank is earned by using the ability",
            0.25, 0.88, 0.25)
    elseif kind == "s" then
        GameTooltip:AddLine("  granted at character creation", 0.8, 0.8, 0.8)
    elseif kind == "q" then
        GameTooltip:AddLine("  quest: " .. tostring(row[R_SRC])
            .. " (" .. tostring(row[R_PLACE]) .. ")", 0.8, 0.8, 0.8)
    else
        local head = "  " .. tostring(row[R_SRC]) .. ", " .. tostring(row[R_PLACE])
        if (row[R_SRCLEVEL] or 0) > 0 then
            head = head .. " (level " .. row[R_SRCLEVEL] .. ")"
        end
        GameTooltip:AddLine(head, 0.8, 0.8, 0.8)
        local alts = row[R_ALTS]
        for i = 1, #(alts or {}) do
            local a = alts[i]
            GameTooltip:AddLine("  " .. tostring(a[1]) .. ", " .. tostring(a[2])
                .. " (level " .. tostring(a[3]) .. ")", 0.65, 0.65, 0.65)
        end
    end

    -- The bounty for this rank's carrier, if the character has not found the book yet. The two
    -- systems have run past each other until now: there is a kill quest for almost every
    -- carrier, and nothing anywhere said so at the moment the question is being asked.
    local b = (bountyOfRank[entry.id] or {})[row[R_ID]]
    if b then
        GameTooltip:AddLine(" ")
        if b[2] == 1 then
            GameTooltip:AddLine("Bounty accepted -- the kill will hand this over.", 0.4, 0.9, 0.4)
        else
            GameTooltip:AddLine("A bounty exists for this creature.", 1, 0.82, 0)
            GameTooltip:AddLine("Letters drop off dungeon trash that carries no tome of its own.",
                0.8, 0.8, 0.8, true)
        end
    end

    if entry.rare then
        GameTooltip:AddLine(" ")
        GameTooltip:AddLine("Every rank of this one comes off a dungeon boss and binds on "
            .. "pickup -- it will never be on the auction house.", 1, 0.5, 0.2, true)
    end
    GameTooltip:Show()
end

