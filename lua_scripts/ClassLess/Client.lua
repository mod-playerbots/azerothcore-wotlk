function MyHandlers.ClassLessOff(player)
    classLessOff = true
    -- The minimap button too. It is built at PLAYER_ENTERING_WORLD, which is before the server
    -- has said whether this character is ours -- so it exists for a moment on every character,
    -- and a Druid should not be left with a button that opens a picker it has no practice for.
    if CLMinimapButton then
        CLMinimapButton:Hide()
    end
    ChoiceHide()
    if CollFrame and CollFrame:IsShown() then
        CollFrame:Hide()
    end
    RestoreTalentUI()
    PracticeBarsRefresh()
end

