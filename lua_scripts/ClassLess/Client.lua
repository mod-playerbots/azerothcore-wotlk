-- The toggle, and the thing that toggles it.
--
-- Everything else in this addon is reachable from a button; the one panel that mattered most was
-- reachable only by being handed to you and then never again. The minimap button is the fix: a
-- place the panel LIVES, which is also where its "you have something waiting" light belongs.
function ToggleChoice()
    if ChoiceHide() then
        return
    end
    local any = false
    for id in pairs(choiceQueue) do
        if offerOf[id] and #offerOf[id] > 1 and offerReady[id] then
            any = true
            break
        end
    end
    if not any then
        Print("Nothing waiting. An ability offers a talent once its practice has earned one.")
        return
    end
    if UnitAffectingCombat("player") or InCombatLockdown() then
        Print("Not in combat -- it will keep.")
        return
    end
    RaiseChoice(true)
end

