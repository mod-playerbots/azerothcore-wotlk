local function BuildView()
    view = {}
    local needle = string.lower(searchText)
    local onlyMissing = CollFrame and CollFrame.missing:GetChecked() and true or false

    local function add(entry)
        if not LineMatches(entry, needle, onlyMissing) then
            return
        end
        view[#view + 1] = {line = entry}
        local rows = rankCache[entry.id]
        if expanded[entry.id] and rows then
            for i = 1, #rows do
                -- With "only missing" on, a line is on the list because SOMETHING in it is
                -- missing; showing the ranks already owned underneath would put back exactly
                -- what the filter was asked to remove.
                if not onlyMissing or rows[i][R_STATE] == STATE_MISSING then
                    view[#view + 1] = {line = entry, row = rows[i]}
                end
            end
        end
        if expanded[entry.id] then
            -- What the earned practice can buy, under the ranks it was earned by. Kept out of
            -- the rank list proper because these are not ranks of this line: one of them is
            -- usually a talent belonging to somewhere else entirely.
            local opts = offerOf[entry.id]
            if opts then
                for i = 1, #opts do
                    view[#view + 1] = {line = entry, opt = opts[i]}
                end
            end
        end
    end

    if needle ~= "" then
        -- A search is over the whole catalogue, not the selected spec -- "where do I get
        -- Fireball" is the question this panel exists for, and the answer must not depend on
        -- guessing which spec Blizzard filed it under.
        --
        -- Sorted as LINES and expanded afterwards. Sorting the flat list instead would let a
        -- rank row drift away from the line it belongs to: table.sort is not stable, and two
        -- lines in different classes can carry the same ability name.
        local hits = {}
        for i = 1, #pages do
            local lines = pages[i].lines
            for j = 1, #lines do
                if LineMatches(lines[j], needle, onlyMissing) then
                    hits[#hits + 1] = lines[j]
                end
            end
        end
        table.sort(hits, function(a, b)
            local an, bn = SpellName(a.id), SpellName(b.id)
            if an ~= bn then return an < bn end
            return a.id < b.id
        end)
        for i = 1, #hits do add(hits[i]) end
    elseif selectedZone then
        -- A zone is a flat list of ranks, not of lines: the same line can appear twice with two
        -- of its ranks on two different mobs here, and collapsing that into one line row would
        -- hide the second. Each row carries the line it belongs to, so the tooltip and the
        -- bounty marker work exactly as they do under a spec.
        local z = zoneRows[selectedZone]
        if z then
            for i = 1, #z.rows do
                local row = z.rows[i]
                if not onlyMissing or row[R_STATE] == STATE_MISSING then
                    local entry = lineOf[z.lineIds[i]]
                    if entry then
                        view[#view + 1] = {line = entry, row = row, zone = true}
                    end
                end
            end
        end
    elseif selectedPage and pages[selectedPage] then
        local lines = pages[selectedPage].lines
        for j = 1, #lines do add(lines[j]) end
    end
end

Rebuild = function()
    if not CollFrame then return end
    BuildNav()
    BuildView()
    RefreshNav()
    RefreshList()
end

