                    btn.count:SetText("|cff40a02b" .. p.owned .. "|r")
                else
                    btn.count:SetText("|cff808080" .. p.owned .. "/" .. p.total .. "|r")
                end
            end
        end
    end
end

RefreshList = function()
    local scroll = CollFrame.listScroll
    FauxScrollFrame_Update(scroll, #view, LIST_ROWS, LIST_ROW_H)
    local offset = FauxScrollFrame_GetOffset(scroll)
    for i = 1, LIST_ROWS do
        local btn = CollFrame.listRows[i]
        local item = view[i + offset]
        if item == nil then
            btn:Hide()
        else
            btn:Show()
            btn.item = item
            if item.opt then
                -- One thing the practice could put the work into. Green when there is an
                -- advance in hand to answer with, grey while it is still being earned.
                --
                -- No number on this row. All the options cost the same single advance, so the
                -- distance belongs to the LINE and is drawn once on the line's own row above.
                local ready = offerReady[item.line.id]
                btn.icon:SetTexture(SpellIcon(item.opt.from or item.opt.rank))
                btn.icon:SetPoint("LEFT", 22, 0)
                btn.icon:SetSize(14, 14)
                btn.icon:Show()
                btn.state:Hide()
                btn.bar:Hide()
                local _, rankText = GetSpellInfo(item.opt.rank)
                local label = SpellName(item.opt.from or item.opt.rank)
                if rankText and rankText ~= "" then
                    label = label .. " |cff909090" .. rankText .. "|r"
                end
                local mine = item.opt.from == item.line.id
                local tint = ready and "|cff40e040" or "|cff707070"
                btn.text:SetPoint("LEFT", 42, 0)
                btn.text:SetText(tint .. (mine and "next rank:" or "talent:") .. "|r " .. label)
                if ready then
                    btn.text:SetTextColor(1, 1, 1)
                    btn.count:SetText("|cff40e040spend|r")
                else
                    btn.text:SetTextColor(0.55, 0.55, 0.55)
                    btn.count:SetText("")
                end
                btn.level:SetText("")
            elseif item.row == nil then
                local e = item.line
                btn.icon:SetTexture(SpellIcon(e.id))
                btn.icon:SetPoint("LEFT", 2, 0)
                btn.icon:SetSize(16, 16)
                -- Show(), because the rank branch below hides it and the scroll frame recycles
                -- these buttons: without this, a row that has once drawn a rank draws every
                -- later line without its icon.
                btn.icon:Show()
                btn.state:Hide()
                local marker = expanded[e.id] and "|cffffd100-|r " or "|cffffd100+|r "
                local name = SpellName(e.id)
                if e.rare then
                    name = name .. " |cffff7f2a*|r"
                end
                -- Visible while scanning, not only once the line is open: a waiting choice is
                -- the one thing on this panel that is asking the reader for something.
                -- Only when something can be taken now. A line that is merely working
                -- toward its next option is not asking the reader for anything.
                if offerOf[e.id] and offerReady[e.id] then
                    name = name .. "  |cff40e040[practice ready]|r"
                end
                -- An advance in hand is the one thing on this row asking for a decision;
                -- otherwise how far into the current rank this ability stands and how many more
                -- presses of it the rest of that rank wants. The server sends the distance with
                -- the state for a line already holding an advance and with the offer for one
                -- that is not, so either may be the live figure.
                local have = practiceLine[e.id]
                local need = practiceNeed[e.id] or offerNeed[e.id]
                local skill = practiceSkill[e.id]
                if have and have >= 1 then
                    name = name .. "  |cff40e040ready|r"
                elseif autoRankLine[e.id] then
                    -- The per cent and the distance below both describe progress toward this
                    -- line's next rank, and this line's next rank is not being worked toward.
                    -- Short here and spelled out in the tooltips; the row is a list.
                    name = name .. "  |cff40a0ffauto rank up|r"
                else
                    -- Both, because they answer different halves of the same question and
                    -- neither can be read off the other: the per cent is curved, so 50% is about
                    -- a third of the work rather than half of it. The per cent is what this
                    -- character has done and the distance is a projection of what is left, which
                    -- is why the projection is the one wearing the "~".
                    if skill and skill > 0 then
                        name = name .. "  |cffa0a0a0" .. skill .. "%|r"
                    end
                    if need and need > 0 then
                        name = name .. "  |cff707070~" .. need .. " presses|r"
                    end
                end
                btn.text:SetPoint("LEFT", 24, 0)
                btn.text:SetText(marker .. name)
                btn.text:SetTextColor(1, 1, 1)
                if e.owned >= e.total then
                    btn.count:SetText("|cff40a02b" .. e.owned .. "/" .. e.total .. "|r")
                elseif e.owned == 0 then
                    btn.count:SetText("|cff808080" .. e.owned .. "/" .. e.total .. "|r")
                else
                    btn.count:SetText("|cffffd100" .. e.owned .. "/" .. e.total .. "|r")
                end
                btn.bar:SetWidth(math.max(1, 60 * e.owned / math.max(e.total, 1)))
                btn.bar:Show()
                btn.level:SetText("|cff707070" .. e.level .. "|r")
            else
                local row = item.row
                btn.icon:Hide()
                btn.bar:Hide()
                local icon = STATE_ICON[row[R_STATE]]
                if icon then
                    btn.state:SetTexture(icon)
                    btn.state:Show()
                else
                    btn.state:Hide()
                end
                local _, rankText = GetSpellInfo(row[R_ID])
                if rankText == nil or rankText == "" then
                    rankText = "Rank 1"
                end
                btn.text:SetPoint("LEFT", 44, 0)
                -- A bounty marker on the row itself, not only in the tooltip: the whole point
                -- is that it is visible while scanning a list of things you do not have.
                local mark = ""
                local b = (bountyOfRank[item.line.id] or {})[row[R_ID]]
                if b then
                    mark = b[2] == 1 and "  |cff40e040[bounty active]|r"
                        or "  |cffffd100[bounty]|r"
                end
                btn.text:SetText("|cffb0b0b0" .. rankText .. "|r   "
                    .. SourceText(row, item.line.id) .. mark)
                if row[R_STATE] == STATE_MISSING then
                    btn.text:SetTextColor(0.62, 0.62, 0.62)
                else
                    btn.text:SetTextColor(0.86, 0.86, 0.86)
                end
                -- The number on every rank: PRESSES of this ability that a WHOLE rank of it
                -- costs -- not what is left of the one in progress, which is the line row's
                -- number and belongs there. The SAME on every rank of the line, because pricing
                -- is flat: the sixteenth rank of Fireball asks what its second did. It still
                -- differs per ABILITY, because it is divided by how often that particular button
                -- gets pressed: about 134 presses of Frostbolt against 22 of Corruption, which
                -- is the same amount of fighting either way. Drawn per row rather than once at
                -- the top so the rank a reader is looking at carries its own answer. Only on the
                -- ranks practice can reach, and only while they are still missing: a rank in
                -- hand is not a distance.
                if row[R_PRESSES] and row[R_STATE] == STATE_MISSING then
                    btn.count:SetText("|cff707070~" .. row[R_PRESSES] .. "|r")
                else
                    btn.count:SetText("")
                end
                btn.level:SetText("|cff707070" .. row[R_LEVEL] .. "|r")
            end
        end
    end
end

