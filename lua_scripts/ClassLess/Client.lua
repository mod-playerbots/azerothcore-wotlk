function MyHandlers.CollPage(player, index, cls, kind, spec, icon, flat)
    local page = {cls = cls, kind = kind, spec = spec, icon = icon or "",
                  lines = {}, owned = 0, total = 0}
    -- Five numbers per line, in the order Server.lua packs them.
    for i = 1, #flat, 5 do
        local entry = {
            id    = flat[i],
