-- One tick of practice on one ability.
--
-- `lineId` is the id of the line's FIRST rank, which is the spell whose plain name this is --
-- "Fireball", never "Fireball (Rank 7)". The scale belongs to the ability, not to the rank
-- standing on it, so the name must not carry one either.
--
-- Silent for a line whose name the client cannot resolve rather than printing an id: a number
-- with no ability behind it tells the reader nothing and looks like a bug.
--
-- The number is a percentage of the rank being worked on, 0 to 100, and it starts over at every
-- rank -- so the sentence means the same thing on the second rank of a talent as on the
-- sixteenth of Frostbolt, which a career-long running total never managed.
--
-- One line a FIGHT, not one a press: `gained` is everything the fight was worth to this ability,
-- and the server sends it already summed. It is 0 when the fight finished a rank, because the
-- move crossed a boundary and the rank's own line has just said so.
function MyHandlers.SkillUp(player, lineId, skill, left, gained, hold)
    if lineId == nil or skill == nil then
        return
    end
    -- Refreshed on every tick, so a line that has just reached its hold says so without the
    -- reader having to open the panel to find out why the bar stopped.
    holdLevel[lineId] = (hold and hold > 0) and hold or nil
    PracticeServerPct(lineId, skill)
    -- Kept current between panel openings. Zero means the server had nothing useful to say --
    -- the press finished a rank -- and the row keeps the last real figure until the next tick
    -- rather than drawing a distance of nothing.
    if left and left > 0 then
        practiceNeed[lineId] = left
    end
    PracticeBarsRefresh()
    local name = GetSpellInfo(lineId)
    if name == nil then
        return
    end
    -- Off by default since the strips went on the action bars: a wide rotation earns on four or
    -- five lines a fight, and five lines of chat after every pull is a paragraph nobody reads.
    -- The number is on the button that earned it. "/tomes chat" turns these back on for anyone
    -- who wants the running commentary.
    if practiceChat then
        if gained and gained > 0 then
            SkillUp(string.format("Your skill in %s has increased to %d%% (+%d%%).",
                name, skill, gained))
        else
            SkillUp(string.format("Your skill in %s has increased to %d%%.", name, skill))
        end
    end
    if CollFrame and CollFrame:IsShown() then
        RefreshList()
    end
end

-- The whole picture, sent when the panel opens and after every purchase. Parallel arrays
-- rather than a map, because that is what AIO carries cheaply.
function MyHandlers.PracticeState(player, lines, amounts, waiting, needs, skillLines,
                                 skillValues, skillLeft)
    practiceLine, practiceNeed = {}, {}
    for i = 1, #(lines or {}) do
        practiceLine[lines[i]] = amounts[i]
        practiceNeed[lines[i]] = needs and needs[i] or 0
    end
    -- Replaced wholesale rather than merged: the server sends every line the character has
    -- practised, so anything missing from the message is a line with no practice on it, and a
    -- merge would keep showing a number for a line a character transfer or a wipe has cleared.
    practiceSkill = {}
    for i = 1, #(skillLines or {}) do
        PracticeServerPct(skillLines[i], skillValues and skillValues[i] or 0)
        -- The distance for every practised line, not only for the ones holding an advance --
        -- which is what `needs` above carries. A line quietly working through a rank is the
        -- common case and it had no number on its row at all.
        if skillLeft and skillLeft[i] then
            practiceNeed[skillLines[i]] = skillLeft[i]
        end
    end
    PracticeBarsRefresh()
    -- The offers arrive in the message just before this one, batched, so by the time we get here
    -- every waiting line should already have its options. This loop is the fallback for the one
    -- that somehow did not, and it is deliberately a fallback rather than the normal path: asking
    -- for each waiting line was how this worked, and "ask" shares a twenty-per-five-seconds
    -- allowance with opening a line, so a reader returning to more than twenty standing choices
    -- had the rest silently dropped -- a marker with nothing behind it, and no prompt raised.
    -- Bounded here for the same reason: whatever is still missing after the batch is a bug worth
    -- one round trip, not twenty.
    local asked = 0
    for i = 1, #(waiting or {}) do
        if offerOf[waiting[i]] == nil and asked < 5 then
            asked = asked + 1
            AIO.Handle(handlerName, "PracticeAsk", waiting[i])
        end
    end
    if CollFrame and CollFrame:IsShown() then
        UpdateHeader()
        BuildView()
        RefreshList()
    end
end

-- What one line's practice can buy. An empty list clears the offer -- the reader may have
-- spent it, or levelled past the point where the option made sense.
--
-- `need` is ONE number for the whole offer, in presses of this line, because every option costs
-- the same single advance. `ready` says whether that advance is in hand: 0 means this is the
-- panel asking what the line COULD buy before anything has been earned, which is drawn the same
-- way but greyed and not clickable.
function MyHandlers.PracticeOffer(player, lineId, ids, froms, need, ready, raise,
        lockIds, lockLines, lockLvls, optLvls)
    offerNeed[lineId] = need or 0
    offerReady[lineId] = (ready == 1)
    local locked = {}
    for i = 1, #(lockIds or {}) do
        locked[i] = { rank = lockIds[i], line = lockLines and lockLines[i],
                      level = lockLvls and lockLvls[i] or 0 }
    end
    offerLocked[lineId] = locked
    if ids == nil or #ids == 0 then
        offerOf[lineId] = nil
    else
        local opts = {}
        for i = 1, #ids do
            opts[i] = { rank = ids[i], from = froms[i] }
        end
        offerOf[lineId] = opts
    end
    local ol = {}
    for i = 1, #(optLvls or {}) do
        ol[i] = optLvls[i]
    end
    offerLvls[lineId] = ol
    -- A real choice with the advance in hand. Whether it comes UP is the server's call, and it
    -- says no for an advance earned mid-play: that lands on a kill, and a full-screen decision
    -- in the middle of a pull is the worst moment to ask for one. The chat line the server
    -- printed is the notification; the choice keeps.
    --
    -- It is raised when the reader asked for it -- opening the line, or logging back in, both of
    -- which send raise 1 -- and even then RaiseChoice holds it until they are out of combat.
    -- Was this reply asked for by name? Taken and cleared here, before either branch, because
    -- BOTH of them have to honour it: /tomes pick on an ability that happens to be holding an
    -- advance must open the same panel as one that is not, and the ready path would otherwise
    -- route through RaiseChoice, which declines to reopen something already shown this session.
    local asked = previewWant[lineId]
    previewWant[lineId] = nil
    if ready == 1 and ids and #ids > 1 then
        if choiceQueue[lineId] == nil then
            choiceQueue[lineId] = true
        end
        if asked then
            choiceShown[lineId] = true
            if UnitAffectingCombat("player") or InCombatLockdown() then
                Print("Not in combat -- it will keep.")
            else
                ShowChoice(lineId)
            end
        elseif raise == 1 then
            RaiseChoice()
        end
    elseif asked then
        -- Nothing takeable, so nothing is queued -- but the reader wanted to look at it, and
        -- looking is the whole point of the command.
        choiceQueue[lineId], choiceShown[lineId] = nil, nil
        if UnitAffectingCombat("player") or InCombatLockdown() then
            Print("Not in combat -- try again when you are out of it.")
        else
            ShowChoice(lineId)
        end
    else
        choiceQueue[lineId], choiceShown[lineId] = nil, nil
        if ChoiceFrame and ChoiceFrame:IsShown() and ChoiceFrame.lineId == lineId then
            ChoiceHide()
        end
    end
    if CollFrame and CollFrame:IsShown() then
        BuildView()
        RefreshList()
    end
end

-- What is worth hunting next. Printed rather than drawn: it is a handful of places to go,
-- which is a thing you read once and then walk to, not a thing you keep a panel open for.
function MyHandlers.CollSuggest(player, ids, srcs, places, kinds)
    suggest = {}
    for i = 1, #(ids or {}) do
        suggest[i] = { id = ids[i], src = srcs[i], place = places[i], kind = kinds[i] }
    end
    if #suggest == 0 then
        Print("Nothing within reach that you have not already found.")
        return
    end
    Print("Worth hunting next:")
    for i = 1, #suggest do
        local e = suggest[i]
        Print("  |cffffd100" .. SpellName(e.id) .. "|r -- "
            .. (e.kind == "b" and "Boss: " or "") .. tostring(e.src)
            .. ", " .. tostring(e.place))
    end
end

-- Blizzard's talent frame is opened by the N key and by the micro button, both of which call
-- this global. Not restored to the stock talent frame on purpose: on a classless realm the
-- built-in one shows a class tree the character does not really have. The collection is the
-- honest thing to put behind that key.
function ToggleTalentFrame()
    if classLessOff then
        -- A Druid's talent frame is a Druid's talent frame.
        if StockToggleTalentFrame then
            return StockToggleTalentFrame()
        end
        return
    end
    ToggleCollection()
end

SLASH_CLASSLESSTOMES1 = "/tomes"
SLASH_CLASSLESSTOMES2 = "/collection"
SLASH_CLASSLESSTOMES3 = "/cl"
SlashCmdList["CLASSLESSTOMES"] = function(msg)
    if classLessOff then
        Print("The collection belongs to the Adventurer class. This character has a class of its "
            .. "own, and learns the way that class learns.")
        return
    end
    -- Verb and the rest, separately. The pattern used to anchor the whole message to letters, so
    -- anything with an argument matched nothing and fell through to opening the collection --
    -- which is how "/tomes pick 403" would have quietly opened the wrong panel. The rest is taken
    -- off the ORIGINAL message, not the lowercased copy: a spell link is case-sensitive.
    local arg = msg and msg:lower():match("^%s*(%a*)") or ""
    local rest = msg and msg:match("^%s*%a*%s*(.-)%s*$") or ""
    if arg == "next" then
        AIO.Handle(handlerName, "CollSuggest")
        return
    elseif arg == "pick" or arg == "picker" then
        -- Bare: toggle whatever is waiting. With an argument: open that ability, waiting or not.
        --
        -- /tomes pick 403, /tomes pick Fireball, or /tomes pick <shift-clicked spell>. The link
        -- form is the one worth having: shift-clicking an ability out of the spellbook drops
        -- "|Hspell:15208|h[Lightning Bolt]|h" into the box, which carries the id of the RANK rather
        -- than of the line. The server turns that into its line, so which rank got clicked does
        -- not matter.
        if rest == "" then
            ToggleChoice()
            return
        end
        local id = tonumber(string.match(rest, "spell:(%d+)")) or tonumber(string.match(rest, "%d+"))
        if id == nil then
            -- A plain name, if it is on an action bar: that is the only place this file learns
            -- names, and it learns them for exactly the abilities a reader is likely to ask about.
            local want = string.lower(string.match(rest, "^%s*(.-)%s*$") or "")
            for name, line in pairs(nameLine) do
                if string.lower(name) == want then
                    id = line
                    break
                end
            end
        end
        if id == nil then
            Print("Usage: /tomes pick <spell id>, or shift-click the ability into the box. "
                .. "A plain name works for anything on your action bars.")
            return
        end
        PreviewChoice(id)
        return
    elseif arg == "bars" then
        PracticeBarsToggle()
        return
    elseif arg == "barsdebug" then
        PracticeBarsReport()
        return
    elseif arg == "chat" then
        PracticeChatToggle()
        return
    end
    ToggleCollection()
end
