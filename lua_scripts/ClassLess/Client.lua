-- Take the talent micro button back out of the UI and point it at the collection instead.
--
-- Blizzard normally keeps this button disabled until level 10 and opens the talent frame
-- with it. On a classless realm the talent frame shows a tree the character does not really
-- have, so the button used to be hidden outright. It is a better home for /tomes than an
-- empty slot in the micro bar: the same place, holding the same kind of thing (what this
-- character has learned), available from level 1.
--
-- UpdateMicroButtons runs on a lot of events (level up, spec change, entering the world) and
-- re-applies stock state from secure code, so the fix-up has to be hooked after it, not
-- applied once.
-- Whether this character is a ClassLess one. Assumed true until the server says otherwise,
-- because that is the common case and because the alternative -- start switched off and wait to
-- be switched on -- leaves the panel dead for the length of a round trip on every login.
--
-- The addon is delivered to the whole realm rather than to the class, so a Druid gets this file
-- too and has to be told to leave the game's own UI alone.
local classLessOff = false

-- Blizzard's, captured before it is replaced further down, so it can be handed back.
local StockToggleTalentFrame = ToggleTalentFrame

-- Returns whether there was a button to work on, so the caller can try again if there was not.
--
-- This used to be called once and give up. If the micro buttons had not been built yet -- and
-- whether they have depends on load order, which an AIO-delivered addon does not control -- the
-- function returned, the hook was never installed, and Blizzard's own UpdateMicroButtons then
-- hid the button for the rest of the session because the character is under level 10.
local function RestoreTalentUI()
    local b = _G["TalentMicroButton"]
    if b == nil then return false end
    if classLessOff then
        -- Not ours. Blizzard's own UpdateMicroButtons decides whether this button is enabled --
        -- it wants level 10 and a talent frame -- and the OnClick it ships with opens that frame.
        -- Both are restored by simply not touching them again; the hook below stands down too.
        b:SetScript("OnClick", function() ToggleTalentFrame() end)
        UpdateMicroButtons()
        return true
    end
    b:Show()
    b:Enable()
    b:SetScript("OnClick", function() ToggleTalentFrame() end)
    if not b.__clHooked then
        b.__clHooked = true
        hooksecurefunc("UpdateMicroButtons", function()
            local m = _G["TalentMicroButton"]
            if m and not classLessOff then
                m:Show()
                m:Enable()
            end
        end)
    end
    return true
end

