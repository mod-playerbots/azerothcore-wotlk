        -- works on 3.3.5 for a spell the character does not know: SetSpellByID does not exist on
        -- this client, and SetSpell wants a spellbook index, which a never-taken talent has not got.
        btn:SetScript("OnEnter", function(self)
            if self.rank == nil then
                return
            end
            self.hl:Show()
            GameTooltip:SetOwner(self, "ANCHOR_RIGHT")
            tipOwn = true
            local ok = pcall(GameTooltip.SetHyperlink, GameTooltip, "spell:" .. self.rank)
            tipOwn = false
            if not ok then
                GameTooltip:Hide()
                return
            end
            if self.locked then
                GameTooltip:AddLine(" ")
                GameTooltip:AddLine(self.lockWhy or "Not available.", 1, 0.5, 0.2)
            end
            GameTooltip:Show()
        end)
        btn:SetScript("OnLeave", function(self)
            self.hl:Hide()
            GameTooltip:Hide()
        end)
        btn:SetScript("OnClick", function(self)
            if self.rank == nil or f.lineId == nil then
                return
            end
            if self.locked then
                Print(self.lockWhy or "That one is not available yet.")
                return
            end
            AIO.Handle(handlerName, "PracticePick", f.lineId, self.rank)
            -- Answered: drop it and move to whatever else is waiting.
            choiceQueue[f.lineId], choiceShown[f.lineId] = nil, nil
            offerOf[f.lineId] = nil
            ChoiceAnimate(f, "out")
            RaiseChoice()
        end)
        btn:Hide()
        card.rows[i] = btn
    end

    -- No postpone button any more. It existed because the prompt used to appear uninvited on a
    -- kill, so there had to be a way to wave it off; the prompt is only raised on request now
    -- (opening the line, logging in, or the minimap button), and a button whose whole job is to
    -- dismiss something the reader just asked for is furniture.
    --
    -- Escape still closes it, and that is not optional: a full-screen frame left up by any bug
    -- would otherwise end the session with no way round it. UISpecialFrames is what wires it.
    tinsert(UISpecialFrames, "CLChoiceFrame")
    f:Hide()
    return f
end

-- Close it the way it opened.
local function ChoiceHide()
    if ChoiceFrame and ChoiceFrame:IsShown() and ChoiceFrame.animDir ~= "out" then
        ChoiceAnimate(ChoiceFrame, "out")
        return true
    end
    return false
end

-- Put the next waiting choice in front of the reader, if now is a fair moment.
--
-- `force` skips the "already shown once" test, which is what the minimap button and /tomes pick
-- want: asking for it again is not the prompt taking the screen, it is the reader opening a panel.
function RaiseChoice(force)
    -- Never in combat. An advance lands on a KILL, so without this the prompt takes the screen
    -- away from somebody who is mid-pull. PLAYER_REGEN_ENABLED calls back when they are out.
    if UnitAffectingCombat("player") or InCombatLockdown() then
        return
    end
    if ChoiceFrame and ChoiceFrame:IsShown() and ChoiceFrame.animDir ~= "out" then
        return
    end
    local lineId, opts
    for id in pairs(choiceQueue) do
        local o = offerOf[id]
        if o and #o > 1 and offerReady[id] and (force or not choiceShown[id]) then
            lineId, opts = id, o
            break
        end
        if o == nil or not offerReady[id] then
            choiceQueue[id] = nil        -- resolved elsewhere, or no longer takeable
        end
    end
    if lineId == nil then
        return
    end
    ShowChoice(lineId)
end

-- Draw the picker for one ability: what it can take now, and everything else it could ever become.
--
-- The same frame serves the earned choice and the preview, and it has to: they are the same
-- question asked at two moments, and a preview that laid the information out differently would be
-- teaching the reader a second screen for no reason. What changes is whether the top rows can be
-- clicked -- with no advance in hand nothing can be spent, so every row is a row you are reading.
function ShowChoice(lineId)
    if ChoiceFrame == nil then
        ChoiceFrame = CreateChoiceFrame()
    end
    local f = ChoiceFrame
    f.lineId = lineId
    local opts = offerOf[lineId] or {}
    local optLvls = offerLvls[lineId]
    local locked = offerLocked[lineId] or {}
    local canTake = (offerReady[lineId] == true) and #opts > 0
    f.card.title:SetText(SpellName(lineId))
    f.card.titleIcon:SetTexture(SpellIcon(lineId))

    local function dress(btn, e)
        btn.hl:Hide()
        btn.rank, btn.locked, btn.lockWhy = e.rank, not e.take, e.why
        btn.icon:SetTexture(SpellIcon(e.line or e.rank))
        -- Desaturated rather than merely dimmed. A greyed icon is the game's own word for "not
        -- yet", and it survives being looked at next to five lit ones, which alpha does not.
        if btn.icon.SetDesaturated then
            btn.icon:SetDesaturated(not e.take)
        end
        if e.take then
            btn.icon:SetAlpha(1)
            btn.iconEdge:SetAlpha(0.8)
            btn.text:SetText(SpellName(e.line or e.rank))
            btn.why:SetText("|cff40e040take|r")
        else
            btn.icon:SetAlpha(0.5)
            btn.iconEdge:SetAlpha(0.35)
            btn.text:SetText("|cff909090" .. SpellName(e.line or e.rank) .. "|r")
            btn.why:SetText(e.caption or "")
        end
        btn:Show()
    end

    -- One list, in level order.
    --
    -- The two halves used to be drawn one after the other, which put five takeable talents on top
    -- and then started the rest again from level 11 -- so the column of levels ran 11, 20, 25, 30,
    -- 30, then 11 again. Read down a level column and you are reading the order things arrive in;
    -- anything else is the reader doing the sort by eye. Ties break on name so the list does not
    -- reshuffle between two openings of the same ability.
    --
    -- "Not offered" -- takeable but past the five this offer holds -- sorts by its own level like
    -- everything else. It is a different complaint from a level gate and has a different answer:
    -- the ORDER in bind.data, which tools/classless-web/binddesk.py is for.
    local list = {}
    for i = 1, #opts do
        local lv = (optLvls and optLvls[i]) or 1
        -- In a preview there is nothing to spend, so a takeable talent is shown by its LEVEL like
        -- every other cell. "Needs an advance" belonged in twenty-five cells at once and says the
        -- same thing the heading already said; the cell's own job is what IT costs.
        list[#list + 1] = { rank = opts[i].rank, line = opts[i].from, level = lv,
                            take = canTake, caption = "Level " .. lv,
                            why = canTake and nil or "Nothing to spend yet -- keep practising it." }
    end
    for i = 1, #locked do
        local lv = locked[i].level or 0
        -- 0 means takeable but past the five this offer holds. A different complaint from a level
        -- gate with a different answer: the ORDER in bind.data, which binddesk.py is for.
        list[#list + 1] = { rank = locked[i].rank, line = locked[i].line,
                            level = (lv > 0) and lv or 1, take = false,
                            caption = (lv > 0) and ("Level " .. lv) or "Not offered",
                            why = (lv > 0) and ("Reaches you at level " .. lv)
                                or "Bound to this ability, but past the five it can offer." }
    end
    table.sort(list, function(a, b)
        if a.level ~= b.level then
            return a.level < b.level
        end
        return SpellName(a.line or a.rank) < SpellName(b.line or b.rank)
    end)

    local n = 0
    for i = 1, #list do
        n = n + 1
        if f.card.rows[n] then
            dress(f.card.rows[n], list[i])
        end
    end
    for i = n + 1, #f.card.rows do
        f.card.rows[i]:Hide()
        f.card.rows[i].rank = nil
    end

    -- The card is whatever the grid needs. Two talents make a short card; twenty-five make a
    -- tall one and it still fits a 768-line screen with room over.
    local gridRows = math.ceil(n / CHOICE_COLS)
    -- The last row carries no gap under it; that is what the card's own bottom padding is for.
    local rowsH = (gridRows > 0) and (gridRows * CHOICE_CELL_H + (gridRows - 1) * CHOICE_GAP) or 0
    f.card.inner:SetHeight(rowsH > 0 and rowsH or 1)
    -- 84 above the grid and 26 below it. The card used to end 20 under the last row of names,
    -- which read as the grid having been cut off rather than finished.
    f.card:SetHeight(84 + rowsH + 26)

