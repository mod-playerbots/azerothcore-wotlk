local function SourceText(row, lineId)
    local kind = row[R_KIND]
    if kind == "l" then
        -- A buff, stance, form, aura, portal or teleport: pressed once and then lived with, so
        -- practice could never price it. The level is what pays.
        return "|cff40a0ffComes with the level|r - yours at " .. tostring(row[R_LEVEL])
    elseif kind == "p" then
        if passiveLine[lineId] then
            return "|cff40e040Earned by practice|r - use the spells it improves"
        end
        return "|cff40e040Earned by practice|r - use the ability"
    elseif kind == "s" then
        return "Known from the start"
    elseif kind == "q" then
        return "Quest: " .. tostring(row[R_SRC]) .. " (" .. tostring(row[R_PLACE]) .. ")"
    end
    local text = tostring(row[R_SRC]) .. " - " .. tostring(row[R_PLACE])
    if (row[R_SRCLEVEL] or 0) > 0 then
        text = text .. " (" .. row[R_SRCLEVEL] .. ")"
    end
    if kind == "b" then
        text = "Boss: " .. text
    end
    local alts = row[R_ALTS]
    if alts and #alts > 0 then
        text = text .. "  |cff808080+" .. #alts .. " more|r"
    end
    return text
end

-- ---------------------------------------------------------------------------------------
-- The two flattened lists the scroll frames page through.
--
-- FauxScrollFrame draws a fixed set of rows and moves an offset over an array, so anything
-- that can be shown -- a collapsed class, an expanded line's ranks -- has to be flattened
-- into that array first rather than nested.
-- ---------------------------------------------------------------------------------------
local function BuildNav()
    nav = {}
    -- Sources first, collapsed by default: it is a second way of reading the same catalogue, not
    -- the main one, and 67 zone rows unfolded on top would bury the class list.
    -- "Sources", not "Zones": since the group rule (2026-09-13) an ability is carried by a KIND
    -- of creature -- "Shadow casters, undead and demons" -- rather than by a creature standing in
    -- one zone, and that is what the server sends in this list.
    nav[#nav + 1] = {header = true, cls = "Sources", zones = true}
    if not zonesCollapsed then
        for i = 1, #zoneList do
            nav[#nav + 1] = {zone = i}
        end
    end
    local lastClass = nil
    for i = 1, #pages do
        local p = pages[i]
        if p.cls ~= lastClass then
            lastClass = p.cls
            nav[#nav + 1] = {header = true, cls = p.cls}
        end
        if not navCollapsed[p.cls] then
            nav[#nav + 1] = {page = i}
        end
    end
end

local function LineMatches(entry, needle, onlyMissing)
    if onlyMissing and entry.owned >= entry.total then
        return false
    end
    if needle == "" then
        return true
    end
    return string.find(string.lower(SpellName(entry.id)), needle, 1, true) ~= nil
end

