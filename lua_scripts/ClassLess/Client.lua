-- This file used to be 2900 lines: an ability-picker panel (class/spec/role tabs, Ability
-- Points, Talent Points, rank buttons, prerequisite locks) and a Tome Journal listing every
-- collectible with its source. The picker is gone for good -- abilities are not SELECTED any
-- more: reading a tome grants the rank outright, and everything past the first rank of a line
-- is earned by using it. There was nothing left for the picker to do.
--
-- The journal came back on 2026-08-27, rebuilt from the other end. It was retired on the
-- argument that the tome items answer "where do I get this" better than a static list: they
-- are named "Tome of <Ability> (Rank N)" and most are BoE, so the auction house is the
-- lookup. That holds for the tradeable majority and fails completely for the rest -- 414
-- tomes bind on pickup and never reach an auction house, and the hint notes that used to
-- point at them were retired the same day. There was no way left to find out what you are
-- missing. /tomes is that way.
--
-- So the client's job is four things:
--
--   1. Resource bars. A classless character can hold Rage or Runic Power without being a
--      Warrior/Druid/Death Knight, and the stock UI only draws the bar for its own class.
--   2. The unlock announcement, so reading a book in your bags has visible feedback.
--   3. Repointing the talent micro button and the N key at the collection panel.
--   4. The collection panel itself.
--
-- NOTHING is shipped to the client but this file, and that has not changed. The nine
-- AIO.AddAddon data files that used to come with it (spells, talents, tomes, roles,
-- roles_view, locks, req, categories, proficiencies -- 571 KB, of which tomes.data alone was
-- 469 KB) were what made the old panel expensive: tomes.data is regenerated by every
-- pipeline run, so its checksum changed every time and forced a fresh download on every
-- client. The panel below carries no data at all. It asks the server, which answers out of
-- tables it already holds in memory -- always current, and including the player's own pool,
-- which a static addon file could never have carried in the first place.

